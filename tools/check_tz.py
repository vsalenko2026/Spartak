def прочитать(ws, адрес):
    v = ws[адрес].value
    if isinstance(v, datetime):
        return v.strftime("%d.%m.%Y")
    return v


def main():
    ap = argparse.ArgumentParser(description="Сверка модели с ТЗ v6.011")
    ap.add_argument("--model", default=str(ROOT / "build" / "recalc" / "база.xlsx"))
    a = ap.parse_args()
    путь = Path(a.model)
    if not путь.exists():
        sys.exit(f"нет {путь}. Сначала: python3 tools/run_model.py --tag база --keep")
    wb = openpyxl.load_workbook(путь, data_only=True)

    сошлось = расхождения = ручные = 0
    строки = []
    for раздел, требование, лист, адрес, ожидание, допуск in ТРЕБОВАНИЯ:
        if лист not in wb.sheetnames:
            строки.append((раздел, требование, адрес, "нет листа", "?", "ЛИСТ"))
            расхождения += 1
            continue
        факт = прочитать(wb[лист], адрес)
        if ожидание is None:
            ручные += 1
            статус = "задано" if факт not in (None, "") else "НЕ ЗАДАНО"
            if статус != "задано":
                расхождения += 1
            строки.append((раздел, требование, адрес, факт, "—", статус))
            continue
        if isinstance(ожидание, str):
            ок = str(факт) == ожидание
        elif isinstance(факт, (int, float)):
            ок = abs(факт - ожидание) <= допуск
        else:
            ок = False
        сошлось += ок
        расхождения += (not ок)
        строки.append((раздел, требование, адрес, факт, ожидание,
                       "OK" if ок else "РАСХОЖДЕНИЕ"))

    print(f"{'п.':<5}{'требование ТЗ v6.011':<46}{'ячейка':<8}"
          f"{'в модели':>16}{'по ТЗ':>16}  статус")
    print("-" * 110)
    for раздел, требование, адрес, факт, ожидание, статус in строки:
        ф = f"{факт:,.4g}".replace(",", " ") if isinstance(факт, (int, float)) else str(факт)[:16]
        о = f"{ожидание:,.4g}".replace(",", " ") if isinstance(ожидание, (int, float)) else str(ожидание)[:16]
        print(f"{раздел:<5}{требование[:45]:<46}{адрес:<8}{ф:>16}{о:>16}  {статус}")
    print("-" * 110)
    print(f"сошлось {сошлось}, расхождений {расхождения}, "
          f"проверяется вручную {ручные}")
    return 1 if расхождения else 0


if __name__ == "__main__":
    sys.exit(main())
