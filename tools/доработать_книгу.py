# -*- coding: utf-8 -*-
"""Точечная доработка присланной книги — без пересборки из исходника.

Обычно модель собирается скриптами `build_user_friendly.py` и `build_v9.py`
из эталона. Но когда книга возвращается от владельца с его правками
вводных и сотнями комментариев, пересборка их затрёт. Тогда правка
вносится сюда: скрипт открывает присланный файл, меняет ровно то, что
просили, и сохраняет. Правка так же воспроизводима и так же видна в
диффе, как и остальные.

    python3 tools/доработать_книгу.py вход.xlsx выход.xlsx

Что делает:

1. Строка «Дети на пике сезона (март)» на дашборде. Среднее за период
   сглаживает сезон, а март — самый полный месяц: по нему считают
   загрузку и планируют закупку формы.
2. Чинит «Срок закрытия займа клубу»: `COUNTIF(диапазон;">0.01")` Excel
   разбирает по локали пользователя, и в русской `0.01` перестаёт быть
   числом — на машине Романа строка показывала 1 месяц вместо 36.
3. Две проверки взамен защиты ввода, которую теряют Google Таблицы: из
   127 ячеек с ограничением после импорта доезжает 84, а тип «целое
   число» пропадает целиком.
4. Вознаграждение ФК приводится к тексту договора: база паушального —
   валовая выручка (п. 3.1 а), ставка роялти растёт по календарю
   10 → 12,5 → 15 % (п. 3.1 д/е/ж), оплата клубу сдвигается на месяц
   вперёд (п. 3.2). Новые вводные — раздел 18 листа «01_Вводные».

Все шаги идемпотентны: повторный прогон на уже доработанной книге ничего
не меняет и пишет «пропуск».

Все добавляемые формулы переносимы: только SUMPRODUCT, MONTH, ISNUMBER,
LEFT, IF — их одинаково считают Excel любой локали, LibreOffice и Google
Таблицы. Ни одного числа внутри текстовой строки.
"""
import sys
from pathlib import Path

import openpyxl
from copy import copy
from openpyxl.styles import Font
from openpyxl.workbook.defined_name import DefinedName
from openpyxl.utils import get_column_letter

ДАШБОРД = "00_Дашборд"
ПРОВЕРКИ = "08_Проверки"
РЕЗУЛЬТАТ = "02_Результат"

# Месяцы на расчётных листах: L..BS, по 12 на год. Строка 5 — даты.
ПЕРВЫЙ_МЕСЯЦ = 12
СТРОКА_ДАТ = 5
ЛЕТ = 5


def _строка(ws, название, кол=2):
    """Номер строки по подписи — номера в книге смещаются, подписи нет."""
    for r in range(1, ws.max_row + 1):
        if ws.cell(r, кол).value == название:
            return r
    raise SystemExit(f"на листе «{ws.title}» нет строки «{название}»")


def _месяцы_года(y):
    """Буквы первого и последнего месяца года y (1..5)."""
    a = get_column_letter(ПЕРВЫЙ_МЕСЯЦ + (y - 1) * 12)
    b = get_column_letter(ПЕРВЫЙ_МЕСЯЦ + y * 12 - 1)
    return a, b


def дети_на_пике(wb, log):
    """Строка «Дети на пике сезона (март)» под средним.

    Март ищется по календарю в строке дат, а не по номеру столбца:
    дата старта модели может быть любой, и привязка к седьмому месяцу
    сезона сломалась бы при её смене."""
    ws = wb[ДАШБОРД]
    if any(ws.cell(r, 2).value == "Дети на пике сезона (март)"
           for r in range(1, ws.max_row + 1)):
        log.append(f"{ДАШБОРД}: строка «Дети на пике сезона (март)» уже есть, "
                   f"пропуск")
        return
    r_среднее = _строка(ws, "Дети, среднее за период")
    r_дети = _строка(wb[РЕЗУЛЬТАТ], "Дети, активные")
    r = r_среднее + 1
    занято = [ws.cell(r, c).value for c in range(2, 11)]
    if any(v is not None for v in занято):
        raise SystemExit(f"строка {r} дашборда не пуста — вставка сдвинет "
                         f"графики и ссылки, нужна ручная разметка")

    ws.cell(r, 2).value = "Дети на пике сезона (март)"
    ws.cell(r, 2).font = copy(ws.cell(r_среднее, 2).font)
    # колонка C — факт сезона 25/26: марта в разделе 17 нет, оставляем пусто
    for c in range(3, 11):
        ws.cell(r, c)._style = copy(ws.cell(r_среднее, c)._style)
    for y in range(1, ЛЕТ + 1):
        a, b = _месяцы_года(y)
        ws.cell(r, 3 + y).value = (
            f"=SUMPRODUCT((MONTH('{РЕЗУЛЬТАТ}'!{a}${СТРОКА_ДАТ}:"
            f"{b}${СТРОКА_ДАТ})=3)*'{РЕЗУЛЬТАТ}'!{a}{r_дети}:{b}{r_дети})")
    # итог — последний март горизонта: суммировать или усреднять пики
    # смысла нет, это «сколько детей в сети на пике»
    последний = get_column_letter(3 + ЛЕТ)
    ws.cell(r, 3 + ЛЕТ + 1).value = f"={последний}{r}"
    ws.cell(r, 3 + ЛЕТ + 2).value = f"={get_column_letter(3 + ЛЕТ + 1)}{r}"
    log.append(f"{ДАШБОРД}: строка {r} «Дети на пике сезона (март)» — "
               f"март ищется по календарю, не по номеру столбца")


def починить_срок_займа(wb, log):
    """COUNTIF с дробным критерием читается по локали и молча даёт ноль."""
    ws = wb[ДАШБОРД]
    r = _строка(ws, "Срок закрытия займа клубу, мес.")
    было = ws.cell(r, 3).value
    было = было.text if hasattr(было, "text") else было
    if было is None or "COUNTIF" not in было:
        log.append(f"{ДАШБОРД}: срок закрытия займа уже без COUNTIF, пропуск")
        return
    r_займ = _строка(wb["06_Деньги"], "Займ на конец")
    первый = get_column_letter(ПЕРВЫЙ_МЕСЯЦ)
    последний = get_column_letter(ПЕРВЫЙ_МЕСЯЦ + ЛЕТ * 12 - 1)
    ws.cell(r, 3).value = (
        f"=IF('06_Деньги'!{последний}{r_займ}>0.01,"
        f"\"не закрыт за {ЛЕТ * 12} мес.\","
        f"SUMPRODUCT(--('06_Деньги'!{первый}{r_займ}:"
        f"{последний}{r_займ}>0.01))+1)")
    log.append(f"{ДАШБОРД}: срок закрытия займа — COUNTIF с критерием "
               f"\">0.01\" заменён на SUMPRODUCT; критерий строкой Excel "
               f"разбирал по локали и в русской возвращал ноль")


def проверки_вместо_защиты(wb, log):
    """Две строки на листе проверок — формулы переживают импорт в Google,
    а ограничения на ввод нет."""
    ws = wb[ПРОВЕРКИ]
    r_посл = _строка(ws, "EBITDA не равна денежному потоку")
    НОВЫЕ = [
        # ISNUMBER обязателен: без него текстовая ячейка сравнивается с
        # числом, а в Excel текст больше любого числа — проверка прошла бы
        # вхолостую на каждой строке. Единица «₽ ±» помечает строки, где
        # минус законен: это факт сезона 25/26, он был убыточным.
        ("Вводные не ушли в минус",
         "=SUMPRODUCT(--ISNUMBER('01_Вводные'!$B$5:$B$339),"
         "--(LEFT('01_Вводные'!$C$5:$C$339,3)<>\"₽ ±\"),"
         "--('01_Вводные'!$B$5:$B$339<0))",
         "Отрицательная ставка, цена или количество тихо ломают расчёт. "
         "В Google Таблицах запрет на ввод импорт не переживает, а эта "
         "проверка переживает"),
        ("Доли и ставки не больше 100 %",
         "=SUMPRODUCT(--ISNUMBER('01_Вводные'!$B$5:$B$339),"
         "--(LEFT('01_Вводные'!$C$5:$C$339,1)=\"%\"),"
         "--('01_Вводные'!$B$5:$B$339>1))",
         "Доля больше единицы означает, что процент введён как 35 вместо "
         "0,35 — самая частая ошибка ввода. Проверяются все строки, у "
         "которых единица измерения начинается с процента"),
    ]
    r = r_посл + 1
    for название, формула, зачем in НОВЫЕ:
        if any(ws.cell(x, 2).value == название
               for x in range(1, ws.max_row + 1)):
            log.append(f"{ПРОВЕРКИ}: «{название}» уже есть, пропуск")
            continue
        for кол in range(2, 6):
            ws.cell(r, кол)._style = copy(ws.cell(r_посл, кол)._style)
        ws.cell(r, 2).value = название
        ws.cell(r, 3).value = формула
        ws.cell(r, 4).value = (f'=IF(ABS(C{r})<0.5,"OK","ПРОВЕРИТЬ")')
        ws.cell(r, 5).value = зачем
        log.append(f"{ПРОВЕРКИ}: строка {r} «{название}»")
        r += 1


# --- Вознаграждение ФК по договору (п. 3.1 а, д/е/ж и п. 3.2) ----------------
#
# Договор разводит базы намеренно: в подпункте а) «35 % от валовой выручки»
# без оговорки, а в д/е/ж — «от валовой выручки за вычетом НДС». Оговорка
# стоит там, где нужна, и в а) её нет; шапка пункта добавляет «в том числе
# НДС по применимой ставке». Значит база паушального — с НДС.
#
# Ставка роялти растёт по календарю, а не по номеру месяца: 10 % до
# 30.06.2027, 12,5 % с 01.07.2027 по 30.06.2029, 15 % с 01.07.2029.
#
# Пункт 3.2 даёт месяц отсрочки: «не позднее 10-го числа месяца, следующего
# за отчётным». Модель платила в месяце начисления, то есть раньше срока.

РАСХОДЫ, ДОХОДЫ = "05_Расходы", "04_Доходы"
ПЕРВЫЙ_СТОЛБЕЦ = 12          # L — первый месяц
ТЕХНИЧЕСКИХ = 6              # столбцы «тех. 1»–«тех. 6» за горизонтом
СТР_ПАУШАЛЬНЫЕ_ФК = 47       # начислено ФК: паушальные
СТР_РОЯЛТИ_ФК = 48           # начислено ФК: роялти
СТР_НАЧИСЛЕНО_ФК = 50        # начислено ФК — всего
СТР_ОПЛАТА_КЛУБУ = 49        # 02_Результат: оплата клубу

# Новый раздел вводных. Ставится в хвост листа: вставка строк рядом со
# строкой 60 сдвинула бы всё ниже, а формулы книги ссылаются на строки
# абсолютно — openpyxl их не переписывает.
ВВОДНЫЕ_ФК = [
    ("18. Вознаграждение ФК по договору", None, None, None, None),
    ("Доля ФК от роялти — 2-я ступень", 0.125, "%", "Договор, п. 3.1 е)",
     "Действует с даты 2-й ступени до даты 3-й."),
    ("Доля ФК от роялти — 3-я ступень", 0.15, "%", "Договор, п. 3.1 ж)",
     "Действует с даты 3-й ступени и до конца горизонта."),
    ("Дата 2-й ступени роялти ФК", "2027-07-01", "дата", "Договор, п. 3.1 е)",
     "До неё действует базовая ставка из B60."),
    ("Дата 3-й ступени роялти ФК", "2029-07-01", "дата", "Договор, п. 3.1 ж)",
     "С неё и далее — ставка 3-й ступени."),
    ("Лаг оплаты клубу", 1, "мес.", "Договор, п. 3.2",
     "Платим не позднее 10-го числа месяца, следующего за отчётным. "
     "0 — платить в месяце начисления, как считала модель раньше."),
]
ИМЕНА_ФК = {2: "ДоляФКРоялти2", 3: "ДоляФКРоялти3",
            4: "ДатаФКСтупень2", 5: "ДатаФКСтупень3", 6: "ЛагОплатыФК"}


def _последний_месяц(ws):
    """Столбец последнего технического месяца — их модель считает тоже."""
    return ws.max_column


def _свободная_строка(ws):
    r = ws.max_row + 2
    for x in range(r, r + len(ВВОДНЫЕ_ФК) + 1):
        if any(ws.cell(x, c).value is not None for c in range(1, 8)):
            raise SystemExit(f"строка {x} листа «{ws.title}» не пуста")
    return r


def вводные_шкалы_фк(wb, log):
    """Раздел 18 на «01_Вводные» плюс имена, чтобы формулы читались."""
    from datetime import datetime
    ws = wb["01_Вводные"]
    if any(ws.cell(r, 1).value == ВВОДНЫЕ_ФК[0][0]
           for r in range(1, ws.max_row + 1)):
        log.append("01_Вводные: раздел 18 уже есть, пропуск")
        return {имя: None for имя in ИМЕНА_ФК.values()}
    старт = _свободная_строка(ws)
    образец = 60          # «Доля ФК от роялти» — с неё берём оформление
    for i, (подпись, знач, ед, источник, зачем) in enumerate(ВВОДНЫЕ_ФК):
        r = старт + i
        for c in range(1, 6):
            ws.cell(r, c)._style = copy(ws.cell(образец, c)._style)
        if i == 0:
            ws.cell(r, 1).font = Font(bold=True)
        if isinstance(знач, str) and знач.count("-") == 2:
            знач = datetime.fromisoformat(знач)
            ws.cell(r, 2).number_format = "DD.MM.YYYY"
        elif ед == "%":
            ws.cell(r, 2).number_format = "0.0%"
        ws.cell(r, 1).value = подпись
        ws.cell(r, 2).value = знач
        ws.cell(r, 3).value = ед
        ws.cell(r, 4).value = источник
        ws.cell(r, 5).value = зачем
    адреса = {}
    for сдвиг, имя in ИМЕНА_ФК.items():
        адрес = f"'01_Вводные'!$B${старт + сдвиг - 1}"
        if имя in wb.defined_names:
            del wb.defined_names[имя]
        wb.defined_names.add(DefinedName(имя, attr_text=адрес))
        адреса[имя] = адрес
    log.append(f"01_Вводные: раздел 18 «Вознаграждение ФК по договору», "
               f"строки {старт}–{старт + len(ВВОДНЫЕ_ФК) - 1}; "
               f"имена {', '.join(ИМЕНА_ФК.values())}")
    return адреса


def паушальный_от_валовой(wb, log):
    """п. 3.1 а): база паушального — валовая выручка, то есть с НДС.

    Строка 13 «Паушальные взносы, с НДС» вместо строки 14 «без НДС»."""
    ws = wb[РАСХОДЫ]
    n = 0
    for c in range(ПЕРВЫЙ_СТОЛБЕЦ, _последний_месяц(ws) + 1):
        cell = ws.cell(СТР_ПАУШАЛЬНЫЕ_ФК, c)
        v, кол = cell.value, cell.column_letter
        if isinstance(v, str) and f"!{кол}14" in v:
            cell.value = v.replace(f"!{кол}14", f"!{кол}13")
            n += 1
    if not n:
        log.append(f"{РАСХОДЫ}: база паушального уже валовая, пропуск")
        return
    # единица измерения на вводной больше не «% без НДС»
    ws = wb["01_Вводные"]
    ws.cell(59, 3).value = "% от суммы с НДС"
    ws.cell(59, 4).value = "Договор, п. 3.1 а)"
    ws.cell(59, 5).value = (
        "«35 % от валовой выручки» — без оговорки «за вычетом НДС», которая "
        "стоит в подпунктах д/е/ж. База считается по строке 13 листа "
        "«04_Доходы» (с НДС), а не по строке 14.")
    log.append(f"{РАСХОДЫ}!{СТР_ПАУШАЛЬНЫЕ_ФК}: база паушального взноса "
               f"переведена на валовую выручку (с НДС), {n} формул")


def _ставка_роялти(кол):
    """Ступенька по календарю: дата месяца лежит в строке 5."""
    return (f"IF({кол}$5>=ДатаФКСтупень3,ДоляФКРоялти3,"
            f"IF({кол}$5>=ДатаФКСтупень2,ДоляФКРоялти2,ДоляФКРоялти))")


def шкала_роялти_фк(wb, log):
    """п. 3.1 д/е/ж: 10 % → 12,5 % → 15 % по календарным датам."""
    n = 0
    for лист, строка in ((РАСХОДЫ, СТР_РОЯЛТИ_ФК),):
        ws = wb[лист]
        for c in range(ПЕРВЫЙ_СТОЛБЕЦ, _последний_месяц(ws) + 1):
            cell = ws.cell(строка, c)
            v = cell.value
            if not isinstance(v, str) or "ДоляФКРоялти" not in v:
                continue
            if "ДатаФКСтупень" in v:      # уже ступенька
                continue
            cell.value = v.replace("ДоляФКРоялти",
                                   _ставка_роялти(cell.column_letter))
            n += 1
    if not n:
        log.append("шкала роялти ФК уже стоит, пропуск")
        return
    ws = wb["01_Вводные"]
    ws.cell(60, 4).value = "Договор, п. 3.1 д)"
    ws.cell(60, 5).value = (
        "Базовая ставка первой ступени. Дальше растёт по календарю — "
        "ступени и их даты в разделе 18. База — за вычетом НДС, как "
        "написано в договоре.")
    log.append(f"шкала роялти ФК: ставка стала ступенькой по календарю, "
               f"{n} формул на «{РАСХОДЫ}»")


def оплата_клубу_по_договору(wb, log):
    """п. 3.2: платим начисление отчётного месяца, месяцем позже.

    Витрина раньше считала долю клуба от роялти заново и брала за базу
    строку поступлений — то есть кассу, а не отчётный месяц. Из-за этого
    клуб недополучал долю с непогашенной дебиторки. Теперь оплата просто
    повторяет «Начислено ФК — всего» с нужного месяца: одна ставка, одно
    место, расхождению взяться неоткуда.

    Переключатель `ЛагОплатыФК` = 0 возвращает оплату в месяц начисления."""
    ws = wb["02_Результат"]
    последний = _последний_месяц(ws)
    if any("ЛагОплатыФК" in str(ws.cell(СТР_ОПЛАТА_КЛУБУ, c).value)
           and f"'{РАСХОДЫ}'!" in str(ws.cell(СТР_ОПЛАТА_КЛУБУ, c).value)
           and "41" not in str(ws.cell(СТР_ОПЛАТА_КЛУБУ, c).value)
           for c in range(ПЕРВЫЙ_СТОЛБЕЦ + 1, последний + 1)):
        log.append("02_Результат: оплата клубу уже по начислению, пропуск")
        return
    for c in range(ПЕРВЫЙ_СТОЛБЕЦ, последний + 1):
        текущий = f"'{РАСХОДЫ}'!{get_column_letter(c)}{СТР_НАЧИСЛЕНО_ФК}"
        прошлый = (f"'{РАСХОДЫ}'!{get_column_letter(c - 1)}{СТР_НАЧИСЛЕНО_ФК}"
                   if c > ПЕРВЫЙ_СТОЛБЕЦ else "0")
        ws.cell(СТР_ОПЛАТА_КЛУБУ, c).value = (
            f"=IF(ЛагОплатыФК=0,{текущий},{прошлый})")
    log.append(f"02_Результат!{СТР_ОПЛАТА_КЛУБУ}: оплата клубу равна "
               f"начислению отчётного месяца со сдвигом на месяц "
               f"(п. 3.2), {последний - ПЕРВЫЙ_СТОЛБЕЦ + 1} формул; раньше "
               f"доля роялти считалась заново от поступлений, то есть от "
               f"кассы")


def проверка_шкалы_фк(wb, log):
    """Ступени должны расти, а даты идти по порядку."""
    ws = wb[ПРОВЕРКИ]
    название = "Шкала роялти ФК согласована"
    if any(ws.cell(r, 2).value == название for r in range(1, ws.max_row + 1)):
        log.append(f"{ПРОВЕРКИ}: «{название}» уже есть, пропуск")
        return
    r_посл = ws.max_row
    while r_посл > 1 and ws.cell(r_посл, 2).value is None:
        r_посл -= 1
    r = r_посл + 1
    for кол in range(2, 6):
        ws.cell(r, кол)._style = copy(ws.cell(r_посл, кол)._style)
    ws.cell(r, 2).value = название
    ws.cell(r, 3).value = (
        "=IF(AND(ДоляФКРоялти<=ДоляФКРоялти2,ДоляФКРоялти2<=ДоляФКРоялти3,"
        "ДатаФКСтупень2<ДатаФКСтупень3),0,1)")
    ws.cell(r, 4).value = f'=IF(C{r}=0,"OK","ПРОВЕРИТЬ")'
    ws.cell(r, 5).value = (
        "Ставки ФК по договору только растут, а дата второй ступени раньше "
        "третьей. Перепутанные местами значения дали бы тихо заниженную "
        "выплату клубу.")
    log.append(f"{ПРОВЕРКИ}: строка {r} «{название}»")


def проверки_на_раздел_18(wb, log):
    """Две общие проверки вводных сканируют B5:B339 — раздел 18 лежит ниже.

    Расширять диапазон до 376 нельзя: между ними таблица факта сезона
    25/26, где в столбце B стоят даты. Поэтому к формуле добавляется
    отдельное слагаемое ровно на строки раздела."""
    ws = wb[ПРОВЕРКИ]
    начало = None
    wi = wb["01_Вводные"]
    for r in range(1, wi.max_row + 1):
        if wi.cell(r, 1).value == ВВОДНЫЕ_ФК[0][0]:
            начало = r + 1
            break
    if начало is None:
        log.append("01_Вводные: раздела 18 нет, проверки не расширяю")
        return
    конец = начало + len(ВВОДНЫЕ_ФК) - 2
    диап = f"'01_Вводные'!$B${начало}:$B${конец}"
    едизм = f"'01_Вводные'!$C${начало}:$C${конец}"
    ХВОСТЫ = {
        "Вводные не ушли в минус":
            f'+SUMPRODUCT(--ISNUMBER({диап}),'
            f'--(LEFT({едизм},3)<>"₽ ±"),--({диап}<0))',
        "Доли и ставки не больше 100 %":
            f'+SUMPRODUCT(--ISNUMBER({диап}),'
            f'--(LEFT({едизм},1)="%"),--({диап}>1))',
    }
    for r in range(1, ws.max_row + 1):
        название = ws.cell(r, 2).value
        хвост = ХВОСТЫ.get(название)
        if not хвост:
            continue
        ф = ws.cell(r, 3).value
        if диап in str(ф):
            log.append(f"{ПРОВЕРКИ}: «{название}» уже видит раздел 18, пропуск")
            continue
        ws.cell(r, 3).value = ф + хвост
        log.append(f"{ПРОВЕРКИ}: «{название}» распространена на раздел 18 "
                   f"(строки {начало}–{конец})")


def подписать_первую_ступень(wb, log):
    """«Доля ФК от роялти» теперь управляет только первыми месяцами.

    Подпись без уточнения читается как ставка на весь горизонт: владелец
    поднимает её на пять пунктов, видит движение EBITDA на миллион вместо
    тридцати и решает, что вводная не работает."""
    ws = wb["01_Вводные"]
    было = ws.cell(60, 1).value
    if было != "Доля ФК от роялти":
        log.append(f"01_Вводные!A60: подпись уже «{было}», пропуск")
        return
    ws.cell(60, 1).value = "Доля ФК от роялти — 1-я ступень"
    log.append("01_Вводные!A60: подпись уточнена — ставка действует только "
               "до даты 2-й ступени, дальше работает раздел 18")


def единица_лага_оплаты(wb, log):
    """«Лаг оплаты клубу» помечен «мес.», а формула сравнивает его с нулём.

    Двойка дала бы тот же один месяц и ничего не сказала бы. Подпись
    относится к разделу 18, то есть к той же правке по договору.

    Подсказка про летнюю посадку живёт отдельно — см. ниже."""
    ws = wb["01_Вводные"]
    строка = None
    for r in range(1, ws.max_row + 1):
        if ws.cell(r, 1).value in ("Лаг оплаты клубу",
                                   "Лаг оплаты клубу: 1 — да, 0 — нет"):
            строка = r
            break
    if строка is None or ws.cell(строка, 3).value == "1 / 0":
        log.append("01_Вводные: единица лага оплаты уже «1 / 0», пропуск")
        return
    ws.cell(строка, 3).value = "1 / 0"
    ws.cell(строка, 1).value = "Лаг оплаты клубу: 1 — да, 0 — нет"
    ws.cell(строка, 5).value = (
        "По договору платим не позднее 10-го числа месяца, следующего за "
        "отчётным. 1 — оплата месяцем позже начисления, 0 — в месяце "
        "начисления, как считала модель раньше. Другие числа формула не "
        "различает: двойка даст тот же один месяц.")
    log.append(f"01_Вводные!C{строка}: единица «мес.» заменена на «1 / 0» — "
               f"формула сравнивает вводную с нулём, а не считает месяцы")


def подсказка_про_лето(wb, log):
    """Подсказка на дашборде называла летнюю посадку шестью процентами.

    Считаем от марта, а не от февраля: мартом дашборд меряет пик сезона
    в строке «Дети на пике сезона (март)», и подсказка должна опираться
    на тот же месяц, иначе два числа рядом меряют от разного.

    Доля и месяцы берутся из индекса посещаемости `01_Вводные!B44:M44`
    при сборке, а не вписываются руками, — поменяют вектор сезонности,
    подсказка пересоберётся под него."""
    ws = wb["01_Вводные"]
    дб = wb[ДАШБОРД]
    МАРТ, ИЮЛЬ, АВГУСТ = 4, 8, 9        # столбцы B..M — январь..декабрь
    март, июль, август = (ws.cell(44, c).value for c in (МАРТ, ИЮЛЬ, АВГУСТ))
    if not all(isinstance(x, (int, float)) for x in (март, июль, август)) \
       or not март:
        log.append("01_Вводные!B44:M44 не числа — подсказку не трогаю")
        return
    доля = f"{round(август / март * 100)} %"
    месяцы = "июле и августе" if июль == август else "августе"
    новое = f"в {месяцы} активны {доля} детей от мартовского уровня"
    for r in range(1, дб.max_row + 1):
        v = дб.cell(r, 2).value
        if not isinstance(v, str) or "детей" not in v:
            continue
        if новое in v:
            log.append(f"{ДАШБОРД}!B{r}: подсказка уже по индексу, пропуск")
            return
        for старое in ("в августе платят 6 % детей",
                       "в июле и августе активны 14 % детей "
                       "от февральского уровня"):
            if старое in v:
                дб.cell(r, 2).value = v.replace(старое, новое)
                log.append(f"{ДАШБОРД}!B{r}: «{старое}» -> «{новое}»")
                return
    log.append(f"{ДАШБОРД}: строки с подсказкой про детей нет, пропуск")


# Светло-зелёная заливка: «это добавлено или изменено правкой по договору».
# Жёлтый на листе вводных уже занят — им помечены ячейки для ввода, и
# перекрашивать их нельзя: правило работы книги говорит менять только
# жёлтые. Поэтому зелёным красится подпись строки, а значение остаётся
# жёлтым.
ЗЕЛЁНЫЙ = "FFC6E0B4"
ПОМЕТКА = "добавлено по договору"


def подсветить_правки(wb, log):
    """Зелёным — всё, что тронула правка по разделу 3 договора."""
    from openpyxl.styles import PatternFill
    заливка = PatternFill("solid", fgColor=ЗЕЛЁНЫЙ)

    ws = wb["01_Вводные"]
    начало = None
    for r in range(1, ws.max_row + 1):
        if ws.cell(r, 1).value == ВВОДНЫЕ_ФК[0][0]:
            начало = r
            break
    if начало is None:
        log.append("01_Вводные: раздела 18 нет, подсветку пропускаю")
        return

    # легенда: пятый образец в ряду «Легенда: ввод / уточнить / переключатель»
    легенда = None
    for r in range(1, 12):
        if ws.cell(r, 1).value == "Легенда:":
            легенда = r
            break
    if легенда and ws.cell(легенда, 5).value != ПОМЕТКА:
        ws.cell(легенда, 5)._style = copy(ws.cell(легенда, 4)._style)
        ws.cell(легенда, 5).value = ПОМЕТКА
        ws.cell(легенда, 5).fill = заливка
        log.append(f"01_Вводные!E{легенда}: в легенду добавлен «{ПОМЕТКА}»")

    ЦЕЛИ = [("01_Вводные", 1, [59, 60] + list(range(начало,
                                                   начало + len(ВВОДНЫЕ_ФК)))),
            (РАСХОДЫ, 2, [СТР_ПАУШАЛЬНЫЕ_ФК, СТР_РОЯЛТИ_ФК]),
            ("02_Результат", 2, [СТР_ОПЛАТА_КЛУБУ])]

    проверки = wb[ПРОВЕРКИ]
    строки = [r for r in range(1, проверки.max_row + 1)
              if проверки.cell(r, 2).value in
              ("Вводные не ушли в минус", "Доли и ставки не больше 100 %",
               "Шкала роялти ФК согласована")]
    ЦЕЛИ.append((ПРОВЕРКИ, 2, строки))

    покрашено = 0
    for лист, кол, ряды in ЦЕЛИ:
        л = wb[лист]
        for r in ряды:
            клетка = л.cell(r, кол)
            if клетка.fill.fgColor.rgb == ЗЕЛЁНЫЙ:
                continue
            клетка.fill = заливка
            покрашено += 1
    if покрашено:
        log.append(f"подсветка: {покрашено} подписей помечены зелёным на "
                   f"листах «01_Вводные», «{РАСХОДЫ}», «02_Результат», "
                   f"«{ПРОВЕРКИ}»")
    else:
        log.append("подсветка: уже стоит, пропуск")


