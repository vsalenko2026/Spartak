def mark_calculated_inputs(wb, log):
    ws = wb["01_Вводные"]
    italic_grey = Font(name="Calibri", size=11, italic=True, color="404040")
    repainted = 0
    for row in ws.iter_rows(min_row=7, max_row=ws.max_row):
        for cell in row:
            if not isinstance(cell.value, str) or not cell.value.startswith("="):
                continue
            coord = cell.coordinate
            if coord in OVERRIDABLE:
                cell.comment = Comment(
                    "ФОРМУЛА ПО УМОЛЧАНИЮ.\n" + OVERRIDABLE[coord], "Модель", 260, 110)
                continue
            current = cell.fill.fgColor.rgb if (cell.fill and cell.fill.patternType) else None
            if current not in (f"FF{GREY}", f"00{GREY}", f"FF{GREEN}", f"00{GREEN}"):
                cell.fill = F_GREY
                repainted += 1
            cell.font = italic_grey
            if coord in SCENARIO_DRIVEN:
                base, mult, name = SCENARIO_DRIVEN[coord]
                txt = (f"РАСЧЁТ, НЕ ВВОДИТЬ — «{name}».\n\n"
                       f"Менять базу здесь: 01_Вводные!{base}.\n")
                if mult:
                    txt += (f"Множитель активного сценария: {mult} "
                            f"(строка сценариев 197–203).\n")
                else:
                    txt += ("Значение — взвешенное среднее по тарифным группам "
                            "(блок 13, строки 263–282): вес × показатель.\n")
                txt += "\nЖёлтая ячейка = ввод. Серая курсивная = формула."
                cell.comment = Comment(txt, "Модель", 300, 150)
            elif cell.comment is None:
                cell.comment = Comment(CALC_NOTE, "Модель", 260, 100)
    log.append(f"01_Вводные: {repainted} расчётных ячеек перекрашено в серый "
               f"(было не отличить от жёлтых вводных)")


