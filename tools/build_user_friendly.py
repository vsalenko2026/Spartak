def link(ws, row, col, text, target):
    """Внутренняя ссылка вида #'Лист'!A1."""
    c = ws.cell(row, col, text)
    c.hyperlink = Hyperlink(ref=c.coordinate, location=target.lstrip("#"))
    c.font = LINK_FONT
    return c


