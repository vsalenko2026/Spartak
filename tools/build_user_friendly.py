def translate_comments(wb, log):
    n = 0
    for name in wb.sheetnames:
        ws = wb[name]
        for row in ws.iter_rows():
            for cell in row:
                if cell.comment is None:
                    continue
                text = (cell.comment.text or "").strip()
                for rx, fn in TRANSLATIONS:
                    m = rx.match(text)
                    if m:
                        cell.comment = Comment(fn(m), "Модель",
                                               cell.comment.width,
                                               cell.comment.height)
                        n += 1
                        break
    log.append(f"переведено англоязычных примечаний: {n}")


