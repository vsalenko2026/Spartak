    очищено = 0
    for r in range(180, 188):
        for c in range(2, 16):
            if v.cell(row=r, column=c).value is not None:
                v.cell(row=r, column=c).value = None
                очищено += 1
    v["A179"] = ("10. История сезона 2025/26 — перенесена в раздел 17 "
                 "(там же помесячный P&L и реестр начислений)")
