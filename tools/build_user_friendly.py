def починить_навигацию(wb, log):
    """Ссылки на разделы, которых при сборке исходника ещё не было.

    В шапке листа шесть настоящих гиперссылок — они работают. Но подпись
    «Раздел 14–16: CAPEX и индексация» осталась от книги, где разделов
    было четырнадцать: теперь 15 — это возврат займа и открытие школ,
    16 — роялти по группам, 17 — история сезона. Ссылка вела в CAPEX и
    обещала не то, а на новые разделы ссылок не было вовсе."""
    from openpyxl.styles import Alignment, Font
    v = wb["01_Вводные"]
    СИНИЙ = Font(color="0563C1", underline="single", size=10)

    def ссылка(адрес, текст, строка):
        # Внутренняя ссылка задаётся location, а не target: строка,
        # присвоенная в hyperlink, становится внешним адресом, и Excel по
        # ней никуда не переходит.
        from openpyxl.worksheet.hyperlink import Hyperlink
        c = v[адрес]
        c.value = текст
        c.hyperlink = Hyperlink(ref=адрес, location=f"'01_Вводные'!A{строка}")
        c.font = СИНИЙ
        c.alignment = Alignment(horizontal="left", vertical="center")

    разделы = {}
    for r in range(1, v.max_row + 1):
        a = str(v.cell(r, 1).value or "").strip()
        m = re.match(r"^(\d+)\.\s", a)
        if m:
            разделы.setdefault(int(m.group(1)), r)

    ссылка("H6", "→ Раздел 14: CAPEX и индексация", разделы[14])
    ссылка("G8", "→ Раздел 15–16: займ, открытие школ, роялти по группам",
           разделы[15])
    ссылка("H8", "→ Раздел 17: история сезона 25/26", разделы[17])
    log.append(f"НАВИГАЦИЯ: подпись H6 исправлена, добавлены ссылки на "
               f"разделы 15 (строка {разделы[15]}) и 17 "
               f"(строка {разделы[17]})")


