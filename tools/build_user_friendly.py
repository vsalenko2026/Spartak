def normalize_links(wb, log):
    """Все внутренние ссылки книги хранились как ВНЕШНИЕ:
    Target="#'01_Вводные'!A1" TargetMode="External", с кириллицей без
    percent-encoding. Excel такое обычно прощает, Google Sheets и строгие
    парсеры — нет. Переводим в каноничный вид location=.
    """
    n = 0
    for name in wb.sheetnames:
        for row in wb[name].iter_rows():
            for cell in row:
                hl = cell.hyperlink
                if hl is None or hl.location:
                    continue
                target = hl.target or ""
                if not target.startswith("#"):
                    continue
                cell.hyperlink = Hyperlink(ref=cell.coordinate,
                                           location=target[1:])
                n += 1
    log.append(f"внутренних ссылок переведено во внутренний формат: {n} "
               f"(были записаны как внешние — ломались вне Excel)")


def fix_broken_links(wb, log):
    for sheet, mapping in BROKEN_LINKS.items():
        ws = wb[sheet]
        for coord, target in mapping.items():
            cell = ws[coord]
            old = cell.hyperlink.location if cell.hyperlink else None
            old_t = cell.hyperlink.target if cell.hyperlink else None
            cell.hyperlink = Hyperlink(ref=coord, location=target)
            cell.font = LINK_FONT
            log.append(f"ссылка {sheet}!{coord}: {old or old_t} -> {target}")


