def _формула_роялти(c, выручка, школы, дата):
    """MAX(фикс; ставка х выручка) внутри каждой группы, сумма наружу.

    MAX внутри SUMPRODUCT не работает поэлементно, поэтому берётся
    тождество MAX(a,b) = (a + b + |a - b|) / 2 — чистая арифметика, она
    считается одинаково в Excel, LibreOffice и Google Sheets.

    Ставка переключается на общую (B57) после даты перехода B245 — так же,
    как это делал котёл до правки."""
    n1, n2 = СТРОКА_ГРУПП + 1, СТРОКА_ГРУПП + len(ГРУППЫ_РОЯЛТИ)
    В = "'01_Вводные'!"
    точек = f"{В}$B${n1}:$B${n2}"
    доля = f"{В}$C${n1}:$C${n2}"
    фикс = f"{В}$D${n1}:$D${n2}"
    ставка = f"{В}$E${n1}:$E${n2}"
    # ставка группы: своя до даты перехода, общая после. Умножение на
    # логическое выражение вместо IF — чтобы диапазон остался массивом.
    ст = (f"({ставка}*({дата}<{В}$B$245)+{В}$B$57*({дата}>={В}$B$245))")
    осталось = f"IF({В}$B$9=0,0,{школы}/{В}$B$9)"
    a = f"{фикс}*{точек}*{осталось}"          # фикс группы
    b = f"{выручка}*{доля}*{ст}"               # процент с выручки группы
    return f"=SUMPRODUCT(({a}+{b}+ABS({a}-{b}))/2)"


