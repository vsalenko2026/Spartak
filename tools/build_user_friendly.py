def _формула_открытий(i, план):
    """Открытия месяца i: первая школа партнёра и следующие за ней.

    Раньше все школы партнёра открывались в один месяц. В жизни партнёр
    сначала запускает одну площадку и только потом берётся за вторую,
    поэтому коэффициент разложен на два слагаемых с разными лагами.
    MIN/MAX держат формулу осмысленной при любом значении B22: меньше
    единицы — вторая площадка просто не появляется."""
    В = "'01_Вводные'!"
    def ветка(лаг, множитель):
        return (f"IF(OR({i}<={лаг},{i}-{лаг}>60),0,"
                f"INDEX({план},1,{i}-{лаг}))*{В}$B$298*{множитель}")
    лаг1 = f"{В}$B$15"
    лаг2 = f"({В}$B$15+{В}$B${СТРОКА_ЛАГ_СЛЕД})"
    return ("=" + ветка(лаг1, f"MIN(1,{В}$B$22)")
            + "+" + ветка(лаг2, f"MAX(0,{В}$B$22-1)"))


