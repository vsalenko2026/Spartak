# --- Модель считается от любой даты старта -----------------------------
#
# Две вещи были привязаны не к календарю, а к номеру столбца, и молча
# ломались при любом старте кроме сентября:
#
#   1. Веса плана продаж (01_Вводные!C36:N40, подписаны Сен…Авг) брались
#      по позиции месяца в сезоне. При старте в декабре декабрь получал
#      сентябрьский вес.
#   2. Согласованный мерч действующей сети (01_Вводные!B99:E101, факт за
#      сентябрь–декабрь 2026) стоял в первых четырёх столбцах листа мерча.
#      При старте в декабре первый месяц забирал сентябрьские 5 070
#      комплектов.
#
# Обе правки нейтральны при старте 1 сентября: проверяется прогоном до и
# после.
СТРОКИ_ПЛАНА = (36, 40)          # веса сезонов 1..5 на 01_Вводные
СТОЛБЦЫ_ПЛАНА = ("C", "N")       # Сен..Авг
СТРОКА_ПРОДАЖ_ВИТРИНА = 15       # 04_Продажи
СТРОКА_ДАТЫ_ПРОДАЖ = 11
СТРОКИ_ПРОДАЖ_ДВИЖОК = [338, 1350, 2362, 3374, 4386]
СМЕЩЕНИЕ_ПЛАНА_СЕЗОНА = -290     # строка плана сезона 1 внутри копии
СТРОКА_МЕРЧА_ФАКТ = 98           # подписи месяцев согласованного мерча
МЕСЯЦЕВ_ФАКТА_МЕРЧА = 4


def _вес_месяца(сезон, дата):
    """Вес календарного месяца в плане продаж сезона.

    Таблица весов подписана Сен…Авг, поэтому колонка ищется как
    «сколько месяцев прошло от сентября», а не по номеру месяца в
    сезоне."""
    r = СТРОКИ_ПЛАНА[0] + сезон - 1
    c1, c2 = СТОЛБЦЫ_ПЛАНА
    диап = f"'01_Вводные'!${c1}${r}:${c2}${r}"
    return f"INDEX({диап},1,MOD(MONTH({дата})-9,12)+1)"


def _формула_продаж(i, дата, план):
    """План сезона, разложенный по календарным месяцам.

    Первый месяц модели продаж не даёт: с нуля за месяц франшизу не
    продать. Его вес вычитается из нормировки первого сезона, поэтому
    годовой план сезона выполняется целиком за оставшиеся месяцы."""
    сезон = min(5, (i - 1) // 12 + 1)
    r = СТРОКИ_ПЛАНА[0] + сезон - 1
    c1, c2 = СТОЛБЦЫ_ПЛАНА
    диап = f"'01_Вводные'!${c1}${r}:${c2}${r}"
    норма = f"SUM({диап})"
    if сезон == 1:
        старт = "'01_Вводные'!$B$7"
        норма = f"({норма}-INDEX({диап},1,MOD(MONTH({старт})-9,12)+1))"
    if i == 1:
        return "=0"
    return f"={план}*{_вес_месяца(сезон, дата)}/{норма}"


def развязать_от_сентября(wb, log):
    """Снимает привязку расчёта к сентябрьскому старту."""
    v = wb["01_Вводные"]

    # 1. Веса сезона 1 были заранее пересчитаны «без сентября»: C36 = 0,
    # остальные поделены на 0,82. Правило «первый месяц без продаж»
    # переезжает в формулу, а таблица становится обычным профилем года —
    # таким же, как у сезонов 2–5.
    эталон = [v.cell(row=37, column=c).value
              for c in range(3, 15)]                 # C37:N37, Сен..Авг
    for c, знач in zip(range(3, 15), эталон):
        v.cell(row=36, column=c).value = знач
    # «2а.», а не «2.»: раздел 2 уже занят продажами и маркетингом, а это
    # его подблок — как «5а.» у согласованного мерча.
    v["A34"] = ("2а. Планы продаж и сезонность (веса — по календарным "
                "месяцам, первый месяц модели без продаж)")

    правок = 0
    p = wb["04_Продажи"]
    for col in range(2, 62):
        c = get_column_letter(col)
        дата = f"{c}${СТРОКА_ДАТЫ_ПРОДАЖ}"
        сезон = min(5, (col - 2) // 12 + 1)
        план = f"'01_Вводные'!$B${СТРОКИ_ПЛАНА[0] + сезон - 1}"
        p.cell(row=СТРОКА_ПРОДАЖ_ВИТРИНА, column=col).value = \
            _формула_продаж(col - 1, дата, план)
        правок += 1

    e = wb["19_Расчет_аналитики"]
    for стр in СТРОКИ_ПРОДАЖ_ДВИЖОК:
        чувствительность = стр in (3374, 4386)
        for col in range(2, 62):
            c = get_column_letter(col)
            дата = f"'06_Сеть_и_дети'!{c}$3"
            i = col - 1
            сезон = min(5, (i - 1) // 12 + 1)
            план = (f"'19_Расчет_аналитики'!$B$"
                    f"{стр + СМЕЩЕНИЕ_ПЛАНА_СЕЗОНА + сезон - 1}")
            ф = _формула_продаж(i, дата, план)
            if чувствительность and ф != "=0":
                ф = f"=IF('01_Вводные'!$B$234=\"Да\",{ф[1:]},0)"
            e.cell(row=стр, column=col).value = ф
            правок += 1
    log.append(f"КАЛЕНДАРЬ: план продаж разложен по календарным месяцам, "
               f"{правок} формул (витрина + {len(СТРОКИ_ПРОДАЖ_ДВИЖОК)} копии)")

    # 2. Согласованный мерч ищется по дате, а не по номеру столбца.
    м = СТРОКА_МЕРЧА_ФАКТ
    # Подписи были текстом «Сен-26»…«Дек-26» — по тексту месяц не найти.
    # Кладём настоящие даты: это факт за конкретные месяцы, он не едет
    # вместе с датой старта.
    for k, c in enumerate(range(2, 6)):
        c_ = v.cell(row=м, column=c)
        c_.value = datetime(2026, 9 + k, 1)
        c_.number_format = "mmm-yy"
    v[f"A{м}"] = "Месяц (факт, ищется по дате)"
    v["A97"] = ("5а. Согласованный мерч действующей сети — факт "
                "сентябрь–декабрь 2026")

    мерч = wb["07_Мерч"]
    РАСЧЁТ = {
        5: "'06_Сеть_и_дети'!{c}19*'01_Вводные'!$B$74*{c}4",
        6: "{c}5*'18_Календарь_тарифы'!{c}10",
        7: "{c}5*'18_Календарь_тарифы'!{c}9",
    }
    ФАКТ = {5: 99, 6: 100, 7: 101}
    мерч_правок = 0
    for стр, шаблон in РАСЧЁТ.items():
        строка_факта = ФАКТ[стр]
        for col in range(2, 68):
            c = get_column_letter(col)
            ключ = f"'01_Вводные'!$B${м}:$E${м}"
            знач = f"'01_Вводные'!$B${строка_факта}:$E${строка_факта}"
            мерч.cell(row=стр, column=col).value = (
                f"=IF(COUNTIF({ключ},{c}$3)>0,SUMIF({ключ},{c}$3,{знач}),"
                f"{шаблон.format(c=c)})")
            мерч_правок += 1
    log.append(f"КАЛЕНДАРЬ: согласованный мерч ищется по дате, "
               f"{мерч_правок} формул на 07_Мерч")

    # Контроль 13_Проверки!60 сравнивал первые четыре столбца мерча с
    # согласованной таблицей. При старте позже сентября часть этих
    # месяцев остаётся за пределами горизонта, и контроль падал на ровном
    # месте. Теперь сравниваются только те согласованные месяцы, которые
    # в горизонт попали.
    пр = wb["13_Проверки"]
    даты = f"'07_Мерч'!$B$3:$BO$3"
    ключ = f"'01_Вводные'!$B${м}:$E${м}"
    пр["A60"] = "Согласованный мерч 2026 не менялся (в пределах горизонта)"
    пр["B60"] = (f"=SUMPRODUCT('07_Мерч'!$B$6:$BO$6*(COUNTIF({ключ},{даты})>0))"
                 f"-SUMPRODUCT('01_Вводные'!$B$100:$E$100"
                 f"*(COUNTIF({даты},{ключ})>0))")
    log.append("КАЛЕНДАРЬ: контроль 13_Проверки!60 сравнивает только те "
               "согласованные месяцы, что попали в горизонт")


# --- Легенда и подписи: чтобы цвета различались, а формулы не падали ---
#
# Код формата внутри TEXT() разбирается языком самого Excel — включая
# десятичный разделитель. «0,0» работает в русском и падает #ЗНАЧ! в
# английском, «0.0» — наоборот. Безопасны только целые placeholder'ы
# («0», «00»), поэтому дробь собирается арифметикой, а не форматом.
ПОДПИСИ_БЕЗ_TEXT = {
    "E13": ('=IF($B$13=0,"Механика работает, пока 0%",'
            '"Закрывается "&ROUND($B$13*100,1)&" % школ и юрлиц в год; '
            'помесячно через коэффициент B14")'),
    "E22": ('="Новый партнёр открывает "&ROUND($B$22,1)&" школы. '
            'Действующая сеть: 2,04 школы на партнёра (104 на 51)"'),
}

# Легенда состояла из четырёх почти одинаковых жёлтых — FFF299, FFF2A0,
# FFF2A5, FFF2CC. На экране они не различались, и «уточнить» читалось как
# обычный ввод. Разводим по цвету, а не по оттенку одного цвета.
ЦВЕТА_ЛЕГЕНДЫ = {
    "FFF299": ("FFF299", "жёлтая — ввод"),
    "FFF2A5": ("FCD5B4", "оранжевая — уточнить"),
    "FFF2A0": ("D9E1F2", "голубая — переключатель"),
    "FFF2CC": ("E4DFEC", "сиреневая — блок ревизии"),
}
