def th(ws, row, col, text):
    c = ws.cell(row, col, text)
    c.font = Font(name="Calibri", size=10, bold=True, color=WHITE)
    c.fill = F_RED
    c.alignment = Alignment(wrap_text=True, vertical="center")
    c.border = BOX
    return c


def link(ws, row, col, text, target):
    """Внутренняя ссылка вида #'Лист'!A1."""
    c = ws.cell(row, col, text)
    c.hyperlink = Hyperlink(ref=c.coordinate, location=target.lstrip("#"))
    c.font = LINK_FONT
    return c


