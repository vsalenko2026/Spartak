def легенда_и_подписи(wb, log):
    """Разводит цвета легенды и убирает TEXT с дробным кодом формата."""
    from openpyxl.styles import Alignment, Font, PatternFill
    v = wb["01_Вводные"]

    for адрес, формула in ПОДПИСИ_БЕЗ_TEXT.items():
        v[адрес] = формула

    перекрашено = 0
    for row in v.iter_rows():
        for c in row:
            if not (c.fill and c.fill.patternType):
                continue
            цвет = str(c.fill.fgColor.rgb or "")[-6:]
            если = ЦВЕТА_ЛЕГЕНДЫ.get(цвет)
            if если and если[0] != цвет:
                c.fill = PatternFill("solid", fgColor=если[0])
                перекрашено += 1

    # Сама строка легенды: короткие подписи, чтобы влезли в колонки.
    v["A2"] = "Легенда:"
    v["A2"].font = Font(bold=True, size=10)
    for адрес, (цвет, подпись) in zip(
            ("B2", "C2", "D2", "E2"),
            [ЦВЕТА_ЛЕГЕНДЫ[k] for k in ("FFF299", "FFF2A5", "FFF2A0",
                                        "FFF2CC")]):
        c = v[адрес]
        c.value = подпись.split(" — ")[1]
        c.fill = PatternFill("solid", fgColor=цвет)
        c.font = Font(bold=True, size=9)
        c.alignment = Alignment(horizontal="center", vertical="center")
    v["F2"] = "формула — не трогать"
    v["F2"].fill = PatternFill("solid", fgColor="F2F2F2")
    v["F2"].font = Font(italic=True, size=9, color="595959")
    v["F2"].alignment = Alignment(horizontal="center", vertical="center")
    v.row_dimensions[2].height = 20

    log.append(f"ЛЕГЕНДА: цвета разведены ({перекрашено} ячеек "
               f"перекрашено), подписи E13 и E22 собраны без TEXT")


