КОЛ_МЕС1_V9 = 12          # L


def найти(ws, название):
    """Номер строки V9.0 по названию в колонке B. Название должно быть
    единственным на листе, иначе сверка сравнивала бы не то, что думает."""
    найдено = [r for r in range(1, ws.max_row + 1)
               if ws.cell(r, 2).value == название]
    if len(найдено) != 1:
        raise SystemExit(f"{ws.title}: строк с названием {название!r} — "
                         f"{len(найдено)}, нужна ровно одна")
    return найдено[0]


def ряд(ws, строка, первый, n=60):
    out = []
    for i in range(n):
        v = ws.cell(row=строка, column=первый + i).value
        out.append(v if isinstance(v, (int, float)) else 0.0)
    return out


def пересчитать(src: Path, tag: str):
    subprocess.run([sys.executable, str(ROOT / "tools" / "run_model.py"),
                    "--model", str(src), "--tag", tag, "--keep"],
                   capture_output=True, text=True, timeout=2400)


def main():
    if not V8.exists():
        пересчитать(ROOT / "model" / "Spartak_V8_9_понятная.xlsx", "база")
    пересчитать(V9_SRC, "v9")
    старая = openpyxl.load_workbook(V8, data_only=True)
    новая = openpyxl.load_workbook(V9, data_only=True)

    print(f"{'показатель':<30}{'V8.9':>16}{'V9.0':>16}{'расхождение':>14}  итог")
    всё_сошлось = True
    for имя, (л8, с8, к8), (л9, с9) in ПАРЫ:
        a = ряд(старая[л8], с8, к8)
        b = ряд(новая[л9], найти(новая[л9], с9), КОЛ_МЕС1_V9)
        плохие = [(i + 1, x, y) for i, (x, y) in enumerate(zip(a, b))
                  if abs(x - y) > max(0.01, abs(x) * 1e-9)]
        статус = "OK" if not плохие else f"расходится в {len(плохие)} мес."
        if плохие:
            всё_сошлось = False
        print(f"{имя:<30}{sum(a):>16,.2f}{sum(b):>16,.2f}"
              f"{sum(b) - sum(a):>14,.2f}  {статус}".replace(",", " "))
        for i, x, y in плохие[:3]:
            print(f"{'':30}  месяц {i}: было {x:,.4f}, стало {y:,.4f}".replace(",", " "))
    print()
    print("ИТОГ: экономика перенесена без изменений" if всё_сошлось
          else "ИТОГ: ЕСТЬ РАСХОЖДЕНИЯ — смотри выше")
    return 0 if всё_сошлось else 1


if __name__ == "__main__":
    sys.exit(main())
