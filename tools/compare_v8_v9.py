"""Сверка V9.0 со старой моделью: та же ли экономика.

Структура другая, поэтому сравниваются не ячейки, а показатели: ряд из
старой книги против ряда из новой, помесячно. Расхождение больше копейки —
ошибка переноса, и она называется по месяцу.

    python3 tools/compare_v8_v9.py
"""
import subprocess
import sys
from pathlib import Path

import openpyxl
from openpyxl.utils import get_column_letter as L

ROOT = Path(__file__).resolve().parent.parent
V8 = ROOT / "build" / "recalc" / "база.xlsx"
V9_SRC = ROOT / "model" / "Spartak_V9_0.xlsx"
V9 = ROOT / "build" / "recalc" / "v9.xlsx"

# показатель: (лист V8, строка V8, первый столбец V8), (лист V9, строка V9)
ПАРЫ = [
    ("Продажи франшиз",          ("04_Продажи", 15, 2), ("03_Сеть", 12)),
    ("Открытия школ",            ("06_Сеть_и_дети", 8, 2), ("03_Сеть", 13)),
    ("Новые юрлица",             ("06_Сеть_и_дети", 9, 2), ("03_Сеть", 14)),
    ("Школы действующей сети",   ("06_Сеть_и_дети", 11, 2), ("03_Сеть", 17)),
    ("Дети действующей, база",   ("06_Сеть_и_дети", 19, 2), ("03_Сеть", 18)),
    ("Дети действующей, активные", ("06_Сеть_и_дети", 20, 2), ("03_Сеть", 19)),
    ("Новые школы 1–12 мес.",     ("06_Сеть_и_дети", 13, 2), ("03_Сеть", 49)),
    ("Новые школы 13–24 мес.",    ("06_Сеть_и_дети", 14, 2), ("03_Сеть", 50)),
    ("Новые школы зрелые",        ("06_Сеть_и_дети", 15, 2), ("03_Сеть", 51)),
    ("Новые школы всего",         ("06_Сеть_и_дети", 16, 2), ("03_Сеть", 52)),
    ("Дети новых, 1–12",          ("06_Сеть_и_дети", 21, 2), ("03_Сеть", 53)),
    ("Дети новых, 13–24",         ("06_Сеть_и_дети", 22, 2), ("03_Сеть", 54)),
    ("Дети новых, зрелые",        ("06_Сеть_и_дети", 23, 2), ("03_Сеть", 55)),
    ("Дети новых всего",          ("06_Сеть_и_дети", 24, 2), ("03_Сеть", 56)),
    ("Юрлица всего",              ("06_Сеть_и_дети", 10, 2), ("03_Сеть", 60)),
    ("Дети всего активные",       ("06_Сеть_и_дети", 25, 2), ("03_Сеть", 61)),
]
КОЛ_МЕС1_V9 = 12          # L


def ряд(ws, строка, первый, n=60):
    out = []
    for i in range(n):
        v = ws.cell(row=строка, column=первый + i).value
        out.append(v if isinstance(v, (int, float)) else 0.0)
    return out


def пересчитать(src: Path, tag: str):
    subprocess.run([sys.executable, str(ROOT / "tools" / "run_model.py"),
                    "--model", str(src), "--tag", tag, "--keep"],
                   capture_output=True, text=True, timeout=2400)


def main():
    if not V8.exists():
        пересчитать(ROOT / "model" / "Spartak_V8_9_понятная.xlsx", "база")
    пересчитать(V9_SRC, "v9")
    старая = openpyxl.load_workbook(V8, data_only=True)
    новая = openpyxl.load_workbook(V9, data_only=True)

    print(f"{'показатель':<30}{'V8.9':>16}{'V9.0':>16}{'расхождение':>14}  итог")
    всё_сошлось = True
    for имя, (л8, с8, к8), (л9, с9) in ПАРЫ:
        a = ряд(старая[л8], с8, к8)
        b = ряд(новая[л9], с9, КОЛ_МЕС1_V9)
        плохие = [(i + 1, x, y) for i, (x, y) in enumerate(zip(a, b))
                  if abs(x - y) > max(0.01, abs(x) * 1e-9)]
        статус = "OK" if not плохие else f"расходится в {len(плохие)} мес."
        if плохие:
            всё_сошлось = False
        print(f"{имя:<30}{sum(a):>16,.2f}{sum(b):>16,.2f}"
              f"{sum(b) - sum(a):>14,.2f}  {статус}".replace(",", " "))
        for i, x, y in плохие[:3]:
            print(f"{'':30}  месяц {i}: было {x:,.4f}, стало {y:,.4f}".replace(",", " "))
    print()
    print("ИТОГ: экономика перенесена без изменений" if всё_сошлось
          else "ИТОГ: ЕСТЬ РАСХОЖДЕНИЯ — смотри выше")
    return 0 if всё_сошлось else 1


if __name__ == "__main__":
    sys.exit(main())
