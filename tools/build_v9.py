def копировать_лист(src_ws, dst_ws, переименовать=None):
    """Переносит лист целиком: значения, формулы, стили, ширины, объединения.

    `переименовать` — замены в текстах формул: имя листа в старой книге
    могло отличаться от нового."""
    for row in src_ws.iter_rows():
        for c in row:
            if c.value is None and not c.has_style:
                continue
            n = dst_ws.cell(row=c.row, column=c.column)
            v = c.value
            if isinstance(v, str) and переименовать:
                for было, стало in переименовать.items():
                    v = v.replace(f"'{было}'!", f"'{стало}'!").replace(
                        f"{было}!", f"{стало}!")
            n.value = v
            if c.has_style:
                n.font = copy(c.font)
                n.fill = copy(c.fill)
                n.border = copy(c.border)
                n.alignment = copy(c.alignment)
                n.number_format = c.number_format
            if c.comment is not None:
                from openpyxl.comments import Comment
                n.comment = Comment(c.comment.text, "Финмодель")
    for буква, dim in src_ws.column_dimensions.items():
        dst_ws.column_dimensions[буква].width = dim.width
        dst_ws.column_dimensions[буква].hidden = dim.hidden
    for i, dim in src_ws.row_dimensions.items():
        dst_ws.row_dimensions[i].height = dim.height
    for rng in src_ws.merged_cells.ranges:
        dst_ws.merge_cells(str(rng))
    dst_ws.sheet_view.showGridLines = src_ws.sheet_view.showGridLines
    dst_ws.freeze_panes = src_ws.freeze_panes


def перенести_имена(старая, новая, log):
    """Имена из старой книги — возрастные ёмкости и минимальные роялти.
    Лист переименован, поэтому ссылки правим."""
    перенесено = 0
    for имя, dn in старая.defined_names.items():
        if имя.startswith("_xlnm"):
            continue
        try:
            текст = dn.value
        except Exception:
            continue
        if "18_Календарь_тарифы" not in текст:
            continue
        новый = текст.replace("'18_Календарь_тарифы'", "'07_Тарифы'").replace(
            "18_Календарь_тарифы", "'07_Тарифы'")
        if имя in новая.defined_names:
            del новая.defined_names[имя]
        новая.defined_names.add(DefinedName(имя, attr_text=новый))
        перенесено += 1
    log.append(f"ИМЕНА: перенесено {перенесено} имён тарифного справочника")


def назвать_вводные(wb, log):
    """Даёт вводным имена: формулы начинают читаться словами."""
    for имя, (адрес, _) in ИМЕНА.items():
        ссылка = f"'01_Вводные'!${адрес[0]}${адрес[1:]}"
        if имя in wb.defined_names:
            del wb.defined_names[имя]
        wb.defined_names.add(DefinedName(имя, attr_text=ссылка))
    log.append(f"ИМЕНА: заведено {len(ИМЕНА)} имён вводных")


def построить_сеть(wb, log):
    """03_Сеть — от плана продаж до детей. Всё прямыми формулами: каждая
    строка читается из вводных и соседних строк этого же листа."""
    л = V.Лист(wb["03_Сеть"], "Сеть: продажи, школы и дети",
               "Расшифровка к «Результату». Считается слева направо: план "
               "продаж → открытия → когорты школ по месяцам жизни → дети.")
    r0 = л.шапка()

    л.блок("Календарь")
    r_дата = л.ряд("Месяц", "=DATE(YEAR(СтартМодели),MONTH(СтартМодели)+{i}-1,1)",
                   "дата", "Отсчёт от даты старта на листе вводных",
                   формат=V.ДАТА, итог="конец")
    r_сезон = л.ряд("Год модели (сезон)", "=INT(({i}-1)/12)+1", "№",
                    "Сезон длится 12 месяцев от старта", формат="0",
                    итог="конец")
    r_месс = л.ряд("Месяц сезона", "=MOD({i}-1,12)+1", "№",
                   "1 = первый месяц сезона (сентябрь)", формат="0",
                   итог="конец")
    r_сез = л.ряд("Сезонность посещаемости",
                  "=INDEX('01_Вводные'!$B$44:$M$44,1,MONTH({м}%d))" % r_дата,
                  "%", "Доля детей, посещающих занятия в этом календарном месяце",
                  формат=V.ПРОЦЕНТ, итог="среднее")

    л.пусто()
    л.блок("Продажи франшиз и открытия")
    r_прод = л.ряд("Продажи франшиз, план",
                   "=INDEX('01_Вводные'!$B$36:$B$40,{м}%d)"
                   "*INDEX('01_Вводные'!$C$36:$N$40,{м}%d,{м}%d)"
                   "/SUM(INDEX('01_Вводные'!$C$36:$N$40,{м}%d,0))"
                   % (r_сезон, r_сезон, r_месс, r_сезон),
                   "шт.", "Годовой план сезона, разложенный по месяцам весами "
                          "из таблицы планов на листе вводных",
                   формат=V.ШТУКИ)
    r_откр = л.ряд("Открытия школ",
                   "=IF({i}-ЛагОткрытия<1,0,INDEX($L%d:$BS%d,1,{i}-ЛагОткрытия))"
                   "*КонверсияОткрытия*ШколНаПродажу" % (r_прод, r_прод),
                   "шт.", "Продажи, сдвинутые на лаг открытия, с поправкой на "
                          "конверсию и число школ на партнёра", формат=V.ШТУКИ)
    r_нюр = л.ряд("Новые юрлица (партнёры)",
                  "={м}%d*ЮрлицНаПродажу" % r_прод,
                  "шт.", "Партнёр появляется в месяц покупки франшизы — "
                         "без лага: лаг нужен школе, а не договору",
                  формат=V.ШТУКИ)

    л.пусто()
    л.блок("Действующая сеть (та, что была на старте)")
    r_дш = л.ряд("Школы действующей сети", "={пред}{r}*КоэффСохранения",
                 "шт.", "Каждый месяц убывает на коэффициент закрытия",
                 первый="=ШколыСтарт*КоэффСохранения", формат=V.ШТУКИ,
                 итог="конец")
    r_дети_база = л.ряд("Дети действующей сети, 100% база",
                        "=ДетиСтарт*(1+РостДетей)^({м}%d-1)"
                        "*IF(ШколыСтарт=0,0,{м}%d/ШколыСтарт)" % (r_сезон, r_дш),
                        "чел.", "База растёт по сезонам и уменьшается вместе "
                                "с числом школ", формат=V.ШТУКИ, итог="конец")
    r_дети_акт = л.ряд("Дети действующей сети, активные",
                       "={м}%d*{м}%d" % (r_дети_база, r_сез),
                       "чел.", "База, умноженная на сезонность посещаемости",
                       формат=V.ШТУКИ, итог="конец")
    л.пусто()
    л.блок("Новые школы по месяцам жизни")
    когорты = []
    предыдущая = None
    for возраст in range(1, 26):
        название = f"{возраст} мес." if возраст < 25 else "25+ мес. (зрелые)"
        if возраст == 1:
            формула = "={м}%d" % r_откр
            первый = "={м}%d" % r_откр
            как = "Школы, открывшиеся в этом месяце"
        elif возраст < 25:
            формула = "={пред}%d*КоэффСохранения" % предыдущая
            первый = "=0"
            как = ""
        else:
            формула = "=({пред}%d+{пред}{r})*КоэффСохранения" % предыдущая
            первый = "=0"
            как = "Школы старше двух лет копятся здесь"
        r = л.ряд(название, формула, "шт.", как, формат=V.ШТУКИ,
                  первый=первый, итог="конец")
        когорты.append(r)
        предыдущая = r

    л.пусто()
    л.блок("Новые школы и их дети")
    r_ш1 = л.ряд("Новые школы 1–12 мес.", "=SUM({м}%d:{м}%d)" % (когорты[0], когорты[11]),
                 "шт.", "Сумма первых двенадцати когорт", формат=V.ШТУКИ, итог="конец")
    r_ш2 = л.ряд("Новые школы 13–24 мес.", "=SUM({м}%d:{м}%d)" % (когорты[12], когорты[23]),
                 "шт.", "Второй год жизни", формат=V.ШТУКИ, итог="конец")
    r_ш3 = л.ряд("Новые школы зрелые", "={м}%d" % когорты[24],
                 "шт.", "Старше двух лет", формат=V.ШТУКИ, итог="конец")
    r_шв = л.ряд("Новые школы — всего", "=SUM({м}%d:{м}%d)" % (r_ш1, r_ш3),
                 "шт.", "", формат=V.ШТУКИ, жирный=True, итог="конец")
    r_д1 = л.ряд("Дети новых школ, 1–12 мес.",
                 "=SUMPRODUCT({м}%d:{м}%d,CapacityYear1)*МножительДетей*{м}%d"
                 % (когорты[0], когорты[11], r_сез),
                 "чел.", "Каждая когорта умножается на ёмкость своего возраста "
                         "из справочника тарифов", формат=V.ШТУКИ, итог="конец")
    r_д2 = л.ряд("Дети новых школ, 13–24 мес.",
                 "=SUMPRODUCT({м}%d:{м}%d,CapacityYear2)*МножительДетей*{м}%d"
                 % (когорты[12], когорты[23], r_сез),
                 "чел.", "", формат=V.ШТУКИ, итог="конец")
    r_д3 = л.ряд("Дети новых школ, зрелые",
                 "={м}%d*CapacityAge25*МножительДетей*{м}%d" % (когорты[24], r_сез),
                 "чел.", "", формат=V.ШТУКИ, итог="конец")
    r_дн = л.ряд("Дети новых школ — всего", "=SUM({м}%d:{м}%d)" % (r_д1, r_д3),
                 "чел.", "", формат=V.ШТУКИ, жирный=True, итог="конец")

    л.пусто()
    л.блок("Итог по сети")
    r_шс = л.ряд("Школы всего", "={м}%d+{м}%d" % (r_дш, r_шв), "шт.",
                 "Действующая сеть плюс новые школы", формат=V.ШТУКИ,
                 жирный=True, итог="конец")
    r_юр = л.ряд("Юрлица (партнёры) всего", "={пред}{r}*КоэффСохранения+{м}%d" % r_нюр,
                 "шт.", "Накопленные партнёры за вычетом закрытий",
                 первый="=ЮрлицаСтарт*КоэффСохранения+$L%d" % r_нюр,
                 формат=V.ШТУКИ, жирный=True, итог="конец")
    r_дв = л.ряд("Дети всего, активные", "={м}%d+{м}%d" % (r_дети_акт, r_дн),
                 "чел.", "Действующая сеть плюс новые школы", формат=V.ШТУКИ,
                 жирный=True, итог="конец")

    log.append(f"03_Сеть: построен полностью — строки {r_дата}–{r_дв}, "
               f"из них 25 когорт школ")
    return {"дата": r_дата, "сезон": r_сезон, "месяц_сезона": r_месс,
            "сезонность": r_сез, "продажи": r_прод, "открытия": r_откр,
            "новые_юрлица": r_нюр, "школы_действ": r_дш,
            "дети_база": r_дети_база, "дети_действ": r_дети_акт,
            "когорты": когорты, "школы_1_12": r_ш1, "школы_13_24": r_ш2,
            "школы_зрелые": r_ш3, "школы_новые": r_шв, "дети_новые": r_дн,
            "школы_всего": r_шс, "юрлица": r_юр, "дети_всего": r_дв,
            "лист": л}


def построить_доходы(wb, сеть, log):
    """04_Доходы — паушальные, роялти и мерч. Роялти новых школ считается
    по возрастам: у каждой когорты своя ёмкость и свой минимальный платёж."""
    С = "'03_Сеть'"
    л = V.Лист(wb["04_Доходы"], "Доходы: паушальные, роялти, мерч",
               "Расшифровка к «Результату». Роялти новых школ разложено по "
               "возрасту школы: чем старше школа, тем больше в ней детей.")
    л.шапка()

    л.блок("Множители периода")
    r_инд = л.ряд("Индекс цен", "='07_Тарифы'!{т}$4", "коэфф.",
                  "Накопленная индексация из справочника тарифов",
                  формат="0.000", итог="конец")
    r_обор = л.ряд("Множитель оборота",
                   "=%s!{м}%d*МножительДетей*МножительЦен*{м}%d"
                   % (С, сеть["сезонность"], r_инд),
                   "коэфф.", "Сезонность, сценарные множители и индексация "
                             "в одном числе", формат="0.000", итог="среднее")
    r_ст_ст = л.ряд("Ставка роялти: договоры до перехода",
                    "={м}%d*IF(%s!{м}%d>=ДатаПереходаСтавки,СтавкаРоялтиВсех,"
                    "СтавкаРоялтиСтарых)" % (r_обор, С, сеть["дата"]),
                    "коэфф.", "После общей даты все переходят на единую ставку",
                    формат="0.0000", итог="среднее")
    r_ст_нов = л.ряд("Ставка роялти: договоры после перехода",
                     "={м}%d*IF(%s!{м}%d>=ДатаПереходаСтавки,СтавкаРоялтиВсех,"
                     "СтавкаРоялтиНовых)" % (r_обор, С, сеть["дата"]),
                     "коэфф.", "", формат="0.0000", итог="среднее")

    л.пусто()
    л.блок("Паушальные взносы")
    r_пауш_ндс = л.ряд("Паушальные взносы, с НДС",
                       "=%s!{м}%d*'07_Тарифы'!{т}$6" % (С, сеть["продажи"]),
                       "₽", "Продажи месяца по тарифу из справочника")
    r_пауш = л.ряд("Паушальные взносы, без НДС",
                   "={м}%d/(1+НДС)" % r_пауш_ндс, "₽", "", жирный=True)

    л.пусто()
    л.блок("Роялти действующей сети")
    r_роялти_д = л.ряд("Роялти действующей сети, с НДС",
                       "=MAX(%s!{м}%d*'07_Тарифы'!{т}$8*IF(%s!{м}%d>="
                       "ДатаПереходаСтавки,СтавкаРоялтиВсех,СтавкаРоялтиСтарых),"
                       "%s!{м}%d*МинРоялтиШкола)"
                       % (С, сеть["дети_действ"], С, сеть["дата"],
                          С, сеть["школы_действ"]),
                       "₽", "Процент с абонементов, но не меньше минимального "
                            "платежа за школу")

    л.пусто()
    л.блок("Школы по возрасту: договоры до перехода на новую ставку")
    r_legacy_откр = л.ряд("Открытия по старым договорам",
                          "=IF({i}-ЛагОткрытия<1,0,IF(INDEX(%s!$L%d:$BS%d,1,"
                          "{i}-ЛагОткрытия)<=ДатаLegacy,%s!{м}%d,0))"
                          % (С, сеть["дата"], сеть["дата"], С, сеть["открытия"]),
                          "шт.", "Школа считается «старой», если франшизу "
                                 "купили до граничной даты", формат=V.ШТУКИ)
    legacy = []
    предыдущая = None
    for возраст in range(1, 26):
        если = "={м}%d" % r_legacy_откр if возраст == 1 else (
            "={пред}%d*КоэффСохранения" % предыдущая if возраст < 25
            else "=({пред}%d+{пред}{r})*КоэффСохранения" % предыдущая)
        r = л.ряд(f"{возраст} мес." if возраст < 25 else "25+ мес.", если,
                  "шт.", "", формат=V.ШТУКИ,
                  первый=("={м}%d" % r_legacy_откр) if возраст == 1 else "=0",
                  итог="конец")
        legacy.append(r)
        предыдущая = r

    def ставка_за_школу(возраст, ставка_строка):
        """Роялти с одной школы данного возраста — как в исходной модели."""
        k = f"{возраст:02d}"
        return (f"IF(РоялтиПоГруппам=\"Да\","
                f"MeanMinAge{k}+{{м}}{ставка_строка}"
                f"*SUMIF(ThresholdAge{k},\"<\"&{{м}}{ставка_строка},WeightedRevAge{k})"
                f"-SUMIF(ThresholdAge{k},\"<\"&{{м}}{ставка_строка},WeightedMinAge{k}),"
                f"MAX(CapacityAge{k}*АбонементНовых*{{м}}{ставка_строка},MeanMinAge{k}))")

    л.пусто()
    л.блок("Роялти новых школ по возрасту — старая ставка")
    стар = []
    for возраст in range(1, 26):
        r = л.ряд(f"{возраст} мес." if возраст < 25 else "25+ мес.",
                  "=IF(OR({м}%d=0,%d<=КаникулыРоялти),0,{м}%d*%s)"
                  % (legacy[возраст - 1], возраст, legacy[возраст - 1],
                     ставка_за_школу(возраст, r_ст_ст)),
                  "₽", "")
        стар.append(r)

    л.пусто()
    л.блок("Роялти новых школ по возрасту — новая ставка")
    нов = []
    когорты = сеть["когорты"]
    for возраст in range(1, 26):
        всего = "%s!{м}%d" % (С, когорты[возраст - 1])
        новых = f"({всего}-{{м}}{legacy[возраст - 1]})"
        r = л.ряд(f"{возраст} мес." if возраст < 25 else "25+ мес.",
                  "=IF(OR(%s=0,%d<=КаникулыРоялти),0,%s*%s)"
                  % (новых, возраст, новых, ставка_за_школу(возраст, r_ст_нов)),
                  "₽", "")
        нов.append(r)

    л.пусто()
    л.блок("Итог по роялти")
    r_роялти_н = л.ряд("Роялти новых школ, с НДС",
                       "=SUM({м}%d:{м}%d)+SUM({м}%d:{м}%d)"
                       % (стар[0], стар[24], нов[0], нов[24]), "₽",
                       "Сумма по всем возрастам и обеим ставкам")
    r_роялти_всего = л.ряд("Роялти всего, с НДС",
                           "={м}%d+{м}%d" % (r_роялти_д, r_роялти_н), "₽", "",
                           жирный=True)
    л.пусто()
    л.блок("Мерч: сколько комплектов покупают")
    r_сез_м = л.ряд("Сезонность повторных покупок",
                    "=INDEX('01_Вводные'!$B$94:$M$94,1,MONTH(%s!{м}%d))"
                    % (С, сеть["дата"]), "%",
                    "Доля годовой закупки, приходящаяся на этот месяц",
                    формат=V.ПРОЦЕНТ, итог="среднее")
    r_компл_д = л.ряд("Действующая сеть — комплекты",
                      "=%s!{м}%d*КоэффМерча*{м}%d" % (С, сеть["дети_база"], r_сез_м),
                      "шт.", "Дети действующей сети по норме комплектов на "
                             "ребёнка, разложено сезонностью", формат=V.ШТУКИ,
                      первый="='01_Вводные'!$B$99")

    # первые четыре месяца действующей сети заданы фактом на листе вводных
    for i, адрес in zip(range(1, 5), ("B", "C", "D", "E")):
        л.ws.cell(row=r_компл_д, column=V.КОЛ_МЕС1 + i - 1).value = \
            f"='01_Вводные'!{адрес}$99"

    r_повтор = []
    л.блок("Школы, покупающие форму повторно (по возрасту)")
    когорты = сеть["когорты"]
    for возраст in range(1, 13):
        # школы моложе пяти месяцев форму повторно не покупают: у них ещё
        # идёт первичная закупка, растянутая на три месяца
        if возраст <= 4:
            формула = "=0"
            как = ("Школы моложе пяти месяцев повторно не закупаются — у них "
                   "ещё идёт первичная закупка") if возраст == 1 else ""
        else:
            формула = ("=IF(AND(ПравилоПовтора=\"Новый сезон\","
                       "%d-1>MOD(MONTH(%s!{м}%d)-9,12)),%s!{м}%d*CapacityAge%02d"
                       "*МножительДетей,0)"
                       % (возраст, С, сеть["дата"], С, когорты[возраст - 1],
                          возраст))
            как = ("Покупают заново, если уже пережили начало сезона"
                   if возраст == 5 else "")
        r = л.ряд(f"{возраст} мес.", формула, "чел.", как,
                  формат=V.ШТУКИ, итог="конец")
        r_повтор.append(r)
    r_повтор_ст = л.ряд("13 мес. и старше",
                        "=SUMPRODUCT(%s!{м}%d:{м}%d,CapacityYear2)*МножительДетей"
                        "+%s!{м}%d*CapacityAge25*МножительДетей"
                        % (С, когорты[12], когорты[23], С, когорты[24]),
                        "чел.", "Школы старше года покупают форму каждый сезон",
                        формат=V.ШТУКИ, итог="конец")
    r_дети_повтор = л.ряд("Дети для повторной формы — всего",
                          "=SUM({м}%d:{м}%d)+{м}%d"
                          % (r_повтор[0], r_повтор[11], r_повтор_ст),
                          "чел.", "", формат=V.ШТУКИ, итог="конец")

    о = сеть["открытия"]
    r_перв = л.ряд("Первичная закупка новых школ, комплекты",
                   "=(%s!{пред}%d*ПервичнаяМес1*КоэффСохранения"
                   "+%s!{пред2}%d*ПервичнаяМес2*КоэффСохранения^2"
                   "+%s!{пред3}%d*ПервичнаяМес3*КоэффСохранения^3)"
                   "*ДетиК12Мес*КоэффМерча" % (С, о, С, о, С, о),
                   "шт.", "Комплекты для только что открывшихся школ: закупка "
                          "растянута на три месяца после открытия",
                   формат=V.ШТУКИ, первый="=0")
    # во втором и третьем месяце слагаемых меньше — предыдущих открытий ещё нет
    л.ws.cell(row=r_перв, column=V.КОЛ_МЕС1 + 1).value = (
        f"=({С}!{V.мес(1)}{о}*ПервичнаяМес1*КоэффСохранения)*ДетиК12Мес*КоэффМерча")
    л.ws.cell(row=r_перв, column=V.КОЛ_МЕС1 + 2).value = (
        f"=({С}!{V.мес(2)}{о}*ПервичнаяМес1*КоэффСохранения"
        f"+{С}!{V.мес(1)}{о}*ПервичнаяМес2*КоэффСохранения^2)*ДетиК12Мес*КоэффМерча")
    r_повт_компл = л.ряд("Повторная закупка новых школ, комплекты",
                         "={м}%d*КоэффМерча*{м}%d" % (r_дети_повтор, r_сез_м),
                         "шт.", "", формат=V.ШТУКИ)

    л.пусто()
    л.блок("Мерч: деньги")
    r_выр_н = л.ряд("Новые школы — выручка с НДС",
                    "=({м}%d+{м}%d)*'07_Тарифы'!{т}$10" % (r_перв, r_повт_компл), "₽", "")
    r_cogs_н = л.ряд("Новые школы — COGS",
                     "=({м}%d+{м}%d)*'07_Тарифы'!{т}$9" % (r_перв, r_повт_компл), "₽", "")
    r_выр_д = л.ряд("Действующая сеть — выручка с НДС",
                    "={м}%d*'07_Тарифы'!{т}$10" % r_компл_д, "₽", "",
                    первый="='01_Вводные'!$B$100")
    r_cogs_д = л.ряд("Действующая сеть — COGS",
                     "={м}%d*'07_Тарифы'!{т}$9" % r_компл_д, "₽", "",
                     первый="='01_Вводные'!$B$101")
    for i, адрес in zip(range(1, 5), ("B", "C", "D", "E")):
        л.ws.cell(row=r_выр_д, column=V.КОЛ_МЕС1 + i - 1).value = f"='01_Вводные'!{адрес}$100"
        л.ws.cell(row=r_cogs_д, column=V.КОЛ_МЕС1 + i - 1).value = f"='01_Вводные'!{адрес}$101"

    r_мерч_ндс = л.ряд("Выручка мерча, с НДС",
                       "={м}%d+{м}%d" % (r_выр_д, r_выр_н), "₽", "")
    r_мерч = л.ряд("Выручка мерча, без НДС", "={м}%d/(1+НДС)" % r_мерч_ндс,
                   "₽", "", жирный=True)
    r_cogs = л.ряд("COGS мерча", "={м}%d+{м}%d" % (r_cogs_д, r_cogs_н), "₽", "")
    r_лог = л.ряд("Логистика, возвраты, брак",
                  "={м}%d*ЛогистикаМерча" % r_мерч, "₽", "")
    r_приб = л.ряд("Прибыль мерча до доли ФК",
                   "=MAX(0,{м}%d-{м}%d-{м}%d)" % (r_мерч, r_cogs, r_лог),
                   "₽", "Ниже нуля не опускается: делить убыток с клубом нечем",
                   жирный=True)

    log.append("04_Доходы: паушальные, роялти по 25 возрастам, мерч")
    return {"паушальные": r_пауш, "паушальные_ндс": r_пауш_ндс,
            "роялти_действ": r_роялти_д, "роялти_новых": r_роялти_н,
            "роялти_всего": r_роялти_всего, "индекс": r_инд,
            "множитель_оборота": r_обор, "legacy": legacy,
            "мерч": r_мерч, "мерч_ндс": r_мерч_ндс, "cogs": r_cogs,
            "логистика": r_лог, "прибыль_мерча": r_приб,
            "комплекты_первичка": r_перв, "комплекты_повтор": r_повт_компл,
            "лист": л}


