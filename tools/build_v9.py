def _график(wb, вид, заголовок, ряды, вторая_ось=(), по="годам",
            высота=9.5, ширина=22, служебные=None):
    """График по строкам расчётных листов.

    `по="годам"` берёт пять годовых колонок и пишет значение прямо на
    точке. `по="месяцам"` берёт 60 месячных: подписи туда не влезут, зато
    видна форма — для кассового разрыва и склада это единственное, что
    имеет смысл.

    `ряды` — список (лист, название строки, подпись, масштаб), где
    масштаб «млн» уводит ряд через служебный блок с уже поделёнными
    значениями. Так подпись выходит «862 млн» и в Excel, и в LibreOffice,
    и в Google Sheets: формат берётся из исходной ячейки, а не из XML
    графика, который читают не все.

    Строки ищутся по названию, поэтому новая строка на листе график не
    ломает."""
    from openpyxl.chart import BarChart, LineChart, Reference
    from openpyxl.chart.label import DataLabelList

    годовой = по == "годам"
    c1 = V.КОЛ_ГОД1 if годовой else V.КОЛ_МЕС1
    c2 = V.КОЛ_ГОД1 + V.ЛЕТ - 1 if годовой else V.КОЛ_МЕС1 + V.МЕСЯЦЕВ - 1
    строка_подписей = 4 if годовой else 5     # «Год 1…Год 5» или даты

    def ссылка(лист, строка, масштаб):
        ws = wb[лист]
        r = _строка(wb, лист, строка)
        if масштаб == "млн" and годовой and служебные is not None:
            r = служебные(лист, r)
            ws = wb["00_Дашборд"]
            return Reference(ws, min_col=c1, max_col=c2, min_row=r, max_row=r)
        return Reference(ws, min_col=c1, max_col=c2, min_row=r, max_row=r)

    def собрать(класс, состав):
        ch = класс()
        ch.style = 2
        for лист, строка, подпись, масштаб in состав:
            ch.append(_ряд(ссылка(лист, строка, масштаб), подпись))
        ws0 = wb[состав[0][0]]
        ch.set_categories(Reference(ws0, min_col=c1, max_col=c2,
                                    min_row=строка_подписей,
                                    max_row=строка_подписей))
        return ch

    def подписать(ch):
        ch.dataLabels = DataLabelList()
        ch.dataLabels.showVal = True
        ch.dataLabels.showSerName = False
        ch.dataLabels.showCatName = False
        ch.dataLabels.showLegendKey = False

    основной = собрать(BarChart if вид == "столбцы" else LineChart, ряды)
    основной.title = заголовок
    основной.height = высота
    основной.width = ширина
    основной.y_axis.numFmt = "#,##0"
    if вид == "столбцы":
        основной.type = "col"
        основной.gapWidth = 60
    if годовой:
        подписать(основной)
    else:
        основной.x_axis.numFmt = "mmm yyyy"
        основной.x_axis.tickLblSkip = 6
        основной.x_axis.tickMarkSkip = 6
    if вторая_ось:
        второй = собрать(LineChart, вторая_ось)
        второй.y_axis.axId = 200
        второй.y_axis.numFmt = "#,##0"
        второй.y_axis.crosses = "max"
        if годовой:
            подписать(второй)
        основной += второй
    return основной


def _ряд(значения, подпись):
    """Ряд с подписью-строкой: заголовок из ячейки взять нельзя — колонки
    значений не соседствуют с колонкой названия."""
    from openpyxl.chart import Series
    return Series(значения, title=подпись)


def починить_подписи_графиков(путь):
    """Проставляет sourceLinked="0" у формата подписей на графиках.

    openpyxl пишет формат подписи как <numFmt formatCode="..."/> без
    признака «формат задан здесь». Excel и LibreOffice в таком случае
    берут формат из исходной ячейки, и подпись выходит рублями на девять
    знаков вместо миллионов. Признак умеет только XML, поэтому он
    дописывается после сохранения книги."""
    import re
    import shutil
    import zipfile

    src = zipfile.ZipFile(путь)
    правок = 0
    имена = src.namelist()
    времянка = путь.with_suffix(".tmp.xlsx")
    with zipfile.ZipFile(времянка, "w", zipfile.ZIP_DEFLATED) as dst:
        for имя in имена:
            данные = src.read(имя)
            if имя.startswith("xl/charts/chart") and имя.endswith(".xml"):
                текст = данные.decode("utf-8")
                текст, n = re.subn(
                    r'<numFmt formatCode="([^"]*)" />',
                    r'<numFmt formatCode="\1" sourceLinked="0" />', текст)
                правок += n
                данные = текст.encode("utf-8")
            dst.writestr(имя, данные)
    src.close()
    shutil.move(времянка, путь)
    return правок


