"""Сборка финмодели V9.0 из V8.9: та же экономика, понятная структура.

Что делает:
  * переносит лист вводных и тарифный справочник (они уже чистые);
  * заново строит расчётные листы прямыми формулами — без цепочек
    «витрина → движок → копия сценария»;
  * раскладывает результат как годы слева, месяцы справа;
  * даёт вводным имена, чтобы формулы читались словами.

Проверка: tools/compare_v8_v9.py сравнивает ключевые ряды новой книги со
старой. Расхождение больше копейки — ошибка переноса.

    python3 tools/build_v9.py
"""
