def _перенаправить_ссылки(wb, log):
    """Ставит на место ссылок, ведших в исчезнувшие листы, аналоги V9.0.

    В V8.9 шапка вводных вела на «00_Старт» и «14а_Сверка_с_ТЗ», а строка
    сценариев — на «03_Сценарии» и «12_Чувствительность». В новой книге
    этих листов нет: оглавление и словарь переехали в «09_Инструкция»,
    контроли — в «08_Проверки», а сценарии перестали быть отдельными
    листами и переключаются на месте. Пустая ячейка на их месте
    выглядела бы потерей, поэтому ссылки перенаправлены."""
    from openpyxl.styles import Font
    from openpyxl.worksheet.hyperlink import Hyperlink
    v = wb["01_Вводные"]
    СИНИЙ = Font(color="0563C1", underline="single", size=10)

    def ссылка(адрес, текст, лист, ячейка="A1"):
        c = v[адрес]
        c.value = текст
        c.hyperlink = Hyperlink(ref=адрес, location=f"'{лист}'!{ячейка}")
        c.font = СИНИЙ

    ссылка("G2", "→ 09_Инструкция: порядок работы, гипотезы, словарь",
           "09_Инструкция")
    ссылка("H2", "→ 08_Проверки: сходится ли модель", "08_Проверки")
    v["D192"] = ("Сценарий переключается здесь: отдельных листов сценариев "
                 "в этой книге нет, вся модель пересчитывается на месте.")
    v["D192"].font = Font(italic=True, size=9, color="595959")
    v["E192"] = None
    log.append("ССЫЛКИ: G2 и H2 перенаправлены на 09_Инструкция и "
               "08_Проверки, строка сценариев объяснена текстом")


def _перенести_ссылку(из_ячейки, в_ячейку, переименовать, книга, потери):
    """Переносит гиперссылку вместе с ячейкой.

    Гиперссылка — отдельный атрибут ячейки: при копировании значения она
    не едет, и переходы по разделам молча перестают работать. В списке
    листа её на этом этапе ещё нет — он собирается при сохранении,
    поэтому берём с самой ячейки.

    Ссылки на листы, которых в новой книге нет («00_Старт»,
    «14а_Сверка_с_ТЗ», «03_Сценарии»), не переносятся: синяя подпись,
    ведущая в никуда, хуже отсутствия подписи."""
    from openpyxl.worksheet.hyperlink import Hyperlink
    место = из_ячейки.hyperlink.location
    if место and переименовать:
        for было, стало in переименовать.items():
            место = место.replace(f"'{было}'!", f"'{стало}'!")
            место = место.replace(f"{было}!", f"{стало}!")
    if место and "!" in место:
        лист = место.split("!")[0].strip("'")
        if лист not in книга.sheetnames:
            потери.append((в_ячейку.coordinate, лист))
            в_ячейку.value = None
            return
    в_ячейку.hyperlink = Hyperlink(
        ref=в_ячейку.coordinate, location=место,
        target=из_ячейки.hyperlink.target,
        tooltip=из_ячейки.hyperlink.tooltip,
        display=из_ячейки.hyperlink.display)


def копировать_лист(src_ws, dst_ws, переименовать=None, потери=None):
    """Переносит лист целиком: значения, формулы, стили, ширины, объединения.

    `переименовать` — замены в текстах формул: имя листа в старой книге
    могло отличаться от нового. `потери` — сюда складываются ссылки,
    которые вели на листы, не доехавшие до новой книги."""
    потери = потери if потери is not None else []
    for row in src_ws.iter_rows():
        for c in row:
            if c.value is None and not c.has_style:
                continue
            n = dst_ws.cell(row=c.row, column=c.column)
            v = c.value
            if isinstance(v, str) and переименовать:
                for было, стало in переименовать.items():
                    v = v.replace(f"'{было}'!", f"'{стало}'!").replace(
                        f"{было}!", f"{стало}!")
            n.value = v
            if c.has_style:
                n.font = copy(c.font)
                n.fill = copy(c.fill)
                n.border = copy(c.border)
                n.alignment = copy(c.alignment)
                n.number_format = c.number_format
            if c.comment is not None:
                from openpyxl.comments import Comment
                n.comment = Comment(c.comment.text, "Финмодель")
            # Гиперссылка — отдельный атрибут ячейки: при копировании
            # значения она не едет, и переходы по разделам молча
            # перестают работать. В списке листа её на этом этапе ещё
            # нет — он собирается при сохранении, поэтому берём с ячейки.
            if c.hyperlink is not None:
                _перенести_ссылку(c, n, переименовать, dst_ws.parent, потери)
    for буква, dim in src_ws.column_dimensions.items():
        dst_ws.column_dimensions[буква].width = dim.width
        dst_ws.column_dimensions[буква].hidden = dim.hidden
    for i, dim in src_ws.row_dimensions.items():
        dst_ws.row_dimensions[i].height = dim.height
    for rng in src_ws.merged_cells.ranges:
        dst_ws.merge_cells(str(rng))
    for dv in src_ws.data_validations.dataValidation:
        dst_ws.add_data_validation(copy(dv))

    dst_ws.sheet_view.showGridLines = src_ws.sheet_view.showGridLines
    dst_ws.freeze_panes = src_ws.freeze_panes


def перенести_имена(старая, новая, log):
    """Имена из старой книги — возрастные ёмкости и минимальные роялти.
    Лист переименован, поэтому ссылки правим."""
    перенесено = 0
    for имя, dn in старая.defined_names.items():
        if имя.startswith("_xlnm"):
            continue
        try:
            текст = dn.value
        except Exception:
            continue
        if "18_Календарь_тарифы" not in текст:
            continue
        новый = текст.replace("'18_Календарь_тарифы'", "'07_Тарифы'").replace(
            "18_Календарь_тарифы", "'07_Тарифы'")
        if имя in новая.defined_names:
            del новая.defined_names[имя]
        новая.defined_names.add(DefinedName(имя, attr_text=новый))
        перенесено += 1
    log.append(f"ИМЕНА: перенесено {перенесено} имён тарифного справочника")


def назвать_вводные(wb, log):
    """Даёт вводным имена: формулы начинают читаться словами."""
    for имя, (адрес, _) in ИМЕНА.items():
        ссылка = f"'01_Вводные'!${адрес[0]}${адрес[1:]}"
        if имя in wb.defined_names:
            del wb.defined_names[имя]
        wb.defined_names.add(DefinedName(имя, attr_text=ссылка))
    строки_групп = _строки_групп(wb)
    for имя, столбец in (("ГруппыТочек", "B"), ("ГруппыДоля", "C"),
                         ("ГруппыФикс", "D"), ("ГруппыСтавка", "E")):
        ссылка = (f"'01_Вводные'!${столбец}${строки_групп[0]}"
                  f":${столбец}${строки_групп[1]}")
        if имя in wb.defined_names:
            del wb.defined_names[имя]
        wb.defined_names.add(DefinedName(имя, attr_text=ссылка))
    log.append(f"ИМЕНА: заведено {len(ИМЕНА)} имён вводных и 4 имени-столбца "
               f"таблицы групп роялти (строки {строки_групп[0]}–{строки_групп[1]})")


def _строки_групп(wb):
    """Границы таблицы групп роялти на листе вводных: находим по заголовку,
    чтобы номера строк не пришлось держать в двух местах."""
    v = wb["01_Вводные"]
    шапка = None
    for r in range(1, v.max_row + 1):
        if v.cell(r, 1).value == "Группа точек начисления":
            шапка = r
            break
    if шапка is None:
        raise SystemExit("01_Вводные: не найдена таблица групп роялти")
    последняя = шапка
    while v.cell(последняя + 1, 1).value not in (None, "Итого"):
        последняя += 1
    return шапка + 1, последняя


def построить_сеть(wb, log):
    """03_Сеть — от плана продаж до детей. Всё прямыми формулами: каждая
    строка читается из вводных и соседних строк этого же листа."""
    л = V.Лист(wb["03_Сеть"], "Сеть: продажи, школы и дети",
               "Расшифровка к «Результату». Считается слева направо: план "
               "продаж → открытия → когорты школ по месяцам жизни → дети.")
    r0 = л.шапка()

    л.блок("Календарь")
    # Календарные строки годовых колонок не получают: год — это период, а
    # не одно значение, и «авг 2027» в колонке «Год 1» читался как будто
    # первый год и есть август 2027. Период теперь написан в шапке.
    r_дата = л.ряд("Месяц", "=DATE(YEAR(СтартМодели),MONTH(СтартМодели)+{i}-1,1)",
                   "дата", "Отсчёт от даты старта на листе вводных",
                   формат=V.ДАТА, итог="конец", годы=False)
    r_сезон = л.ряд("Год модели (сезон)", "=INT(({i}-1)/12)+1", "№",
                    "Сезон длится 12 месяцев от старта", формат="0",
                    итог="конец", годы=False)
    r_месс = л.ряд("Месяц сезона", "=MOD({i}-1,12)+1", "№",
                   "1 = первый месяц сезона от даты старта", формат="0",
                   итог="конец", годы=False)
    r_сез = л.ряд("Сезонность посещаемости",
                  "=INDEX('01_Вводные'!$B$44:$M$44,1,MONTH({м}%d))" % r_дата,
                  "%", "Доля детей, посещающих занятия в этом календарном месяце",
                  формат=V.ПРОЦЕНТ, итог="среднее")

    л.пусто()
    л.блок("Продажи франшиз и открытия")
    # Веса плана подписаны Сен…Авг, поэтому колонка ищется по календарному
    # месяцу, а не по номеру месяца в сезоне: иначе при старте в декабре
    # декабрь получал бы сентябрьский вес. Первый месяц модели продаж не
    # даёт — с нуля за месяц франшизу не продать, — и его вес вычитается
    # из нормировки первого сезона, чтобы годовой план всё равно выполнился.
    веса = "INDEX('01_Вводные'!$C$36:$N$40,{м}%d,MOD(MONTH({м}%d)-9,12)+1)" \
        % (r_сезон, r_дата)
    норма = ("(SUM(INDEX('01_Вводные'!$C$36:$N$40,{м}%d,0))"
             "-IF({i}<=12,INDEX('01_Вводные'!$C$36:$N$40,{м}%d,"
             "MOD(MONTH(СтартМодели)-9,12)+1),0))" % (r_сезон, r_сезон))
    r_прод = л.ряд("Продажи франшиз, план",
                   "=IF(OR({i}>%d,{i}=1),0,"
                   "INDEX('01_Вводные'!$B$36:$B$40,{м}%d)*%s/%s)"
                   % (V.МЕСЯЦЕВ, r_сезон, веса, норма),
                   "шт.", "Годовой план сезона, разложенный по календарным "
                          "месяцам весами из таблицы планов. Первый месяц — "
                          "без продаж. За горизонтом продаж нет: технические "
                          "месяцы нужны только для склада",
                   формат=V.ШТУКИ)
    # Партнёр открывает школы не разом: сначала одну площадку, следующие —
    # через отдельный лаг. MIN/MAX держат формулу осмысленной при любом
    # значении ШколНаПродажу: меньше единицы — второй площадки просто нет.
    def _открытия(лаг, множитель):
        return (f"IF({{i}}-{лаг}<1,0,INDEX($L{r_прод}:$BY{r_прод},1,"
                f"{{i}}-{лаг}))*КонверсияОткрытия*{множитель}")
    r_откр = л.ряд("Открытия школ",
                   "=" + _открытия("ЛагОткрытия", "MIN(1,ШколНаПродажу)")
                   + "+" + _открытия("(ЛагОткрытия+ЛагСледующихШкол)",
                                     "MAX(0,ШколНаПродажу-1)"),
                   "шт.", "Первая школа партнёра — через лаг открытия, "
                          "следующие — ещё через лаг B311. Обе ветки с "
                          "поправкой на конверсию продажи в открытие",
                   формат=V.ШТУКИ)
    r_нюр = л.ряд("Новые юрлица (партнёры)",
                  "={м}%d*ЮрлицНаПродажу" % r_прод,
                  "шт.", "Партнёр появляется в месяц покупки франшизы — "
                         "без лага: лаг нужен школе, а не договору",
                  формат=V.ШТУКИ)

    л.пусто()
    л.блок("Действующая сеть (та, что была на старте)")
    r_дш = л.ряд("Школы действующей сети", "={пред}{r}*КоэффСохранения",
                 "шт.", "Каждый месяц убывает на коэффициент закрытия",
                 первый="=ШколыСтарт*КоэффСохранения", формат=V.ШТУКИ,
                 итог="конец")
    r_дети_база = л.ряд("Дети действующей сети, 100% база",
                        "=ДетиСтарт*(1+РостДетей)^({м}%d-1)"
                        "*IF(ШколыСтарт=0,0,{м}%d/ШколыСтарт)" % (r_сезон, r_дш),
                        "чел.", "База растёт по сезонам и уменьшается вместе "
                                "с числом школ", формат=V.ШТУКИ, итог="конец")
    r_дети_акт = л.ряд("Дети действующей сети, активные",
                       "={м}%d*{м}%d" % (r_дети_база, r_сез),
                       "чел.", "База, умноженная на сезонность посещаемости",
                       формат=V.ШТУКИ, итог="конец")
    л.пусто()
    л.блок("Новые школы по месяцам жизни")
    когорты = []
    предыдущая = None
    for возраст in range(1, 26):
        название = f"{возраст} мес." if возраст < 25 else "25+ мес. (зрелые)"
        if возраст == 1:
            формула = "={м}%d" % r_откр
            первый = "={м}%d" % r_откр
            как = "Школы, открывшиеся в этом месяце"
        elif возраст < 25:
            формула = "={пред}%d*КоэффСохранения" % предыдущая
            первый = "=0"
            как = ""
        else:
            формула = "=({пред}%d+{пред}{r})*КоэффСохранения" % предыдущая
            первый = "=0"
            как = "Школы старше двух лет копятся здесь"
        # Когорта — это школы одного возраста в одном месяце. Складывать
        # такие строки по годам нельзя: одна и та же школа попадёт в сумму
        # двенадцать раз. Годовые колонки поэтому не заполняются, итог по
        # школам собирается ниже в блоке «Новые школы и их дети».
        r = л.ряд(название, формула, "шт.", как, формат=V.ШТУКИ,
                  первый=первый, итог="конец", годы=False)
        когорты.append(r)
        предыдущая = r

    л.пусто()
    л.блок("Новые школы и их дети")
    r_ш1 = л.ряд("Новые школы 1–12 мес.", "=SUM({м}%d:{м}%d)" % (когорты[0], когорты[11]),
                 "шт.", "Сумма первых двенадцати когорт", формат=V.ШТУКИ, итог="конец")
    r_ш2 = л.ряд("Новые школы 13–24 мес.", "=SUM({м}%d:{м}%d)" % (когорты[12], когорты[23]),
                 "шт.", "Второй год жизни", формат=V.ШТУКИ, итог="конец")
    r_ш3 = л.ряд("Новые школы зрелые", "={м}%d" % когорты[24],
                 "шт.", "Старше двух лет", формат=V.ШТУКИ, итог="конец")
    r_шв = л.ряд("Новые школы — всего", "=SUM({м}%d:{м}%d)" % (r_ш1, r_ш3),
                 "шт.", "", формат=V.ШТУКИ, жирный=True, итог="конец")
    r_д1 = л.ряд("Дети новых школ, 1–12 мес.",
                 "=SUMPRODUCT({м}%d:{м}%d,CapacityYear1)*МножительДетей*{м}%d"
                 % (когорты[0], когорты[11], r_сез),
                 "чел.", "Каждая когорта умножается на ёмкость своего возраста "
                         "из справочника тарифов", формат=V.ШТУКИ, итог="конец")
    r_д2 = л.ряд("Дети новых школ, 13–24 мес.",
                 "=SUMPRODUCT({м}%d:{м}%d,CapacityYear2)*МножительДетей*{м}%d"
                 % (когорты[12], когорты[23], r_сез),
                 "чел.", "", формат=V.ШТУКИ, итог="конец")
    r_д3 = л.ряд("Дети новых школ, зрелые",
                 "={м}%d*CapacityAge25*МножительДетей*{м}%d" % (когорты[24], r_сез),
                 "чел.", "", формат=V.ШТУКИ, итог="конец")
    r_дн = л.ряд("Дети новых школ — всего", "=SUM({м}%d:{м}%d)" % (r_д1, r_д3),
                 "чел.", "", формат=V.ШТУКИ, жирный=True, итог="конец")

    л.пусто()
    л.блок("Итог по сети")
    r_шс = л.ряд("Школы всего", "={м}%d+{м}%d" % (r_дш, r_шв), "шт.",
                 "Действующая сеть плюс новые школы", формат=V.ШТУКИ,
                 жирный=True, итог="конец")
    r_юр = л.ряд("Юрлица (партнёры) всего", "={пред}{r}*КоэффСохранения+{м}%d" % r_нюр,
                 "шт.", "Накопленные партнёры за вычетом закрытий",
                 первый="=ЮрлицаСтарт*КоэффСохранения+$L%d" % r_нюр,
                 формат=V.ШТУКИ, жирный=True, итог="конец")
    r_дв = л.ряд("Дети всего, активные", "={м}%d+{м}%d" % (r_дети_акт, r_дн),
                 "чел.", "Действующая сеть плюс новые школы", формат=V.ШТУКИ,
                 жирный=True, итог="конец")

    log.append(f"03_Сеть: построен полностью — строки {r_дата}–{r_дв}, "
               f"из них 25 когорт школ")
    return {"дата": r_дата, "сезон": r_сезон, "месяц_сезона": r_месс,
            "сезонность": r_сез, "продажи": r_прод, "открытия": r_откр,
            "новые_юрлица": r_нюр, "школы_действ": r_дш,
            "дети_база": r_дети_база, "дети_действ": r_дети_акт,
            "когорты": когорты, "школы_1_12": r_ш1, "школы_13_24": r_ш2,
            "школы_зрелые": r_ш3, "школы_новые": r_шв, "дети_новые": r_дн,
            "школы_всего": r_шс, "юрлица": r_юр, "дети_всего": r_дв,
            "лист": л}


def построить_доходы(wb, сеть, log):
    """04_Доходы — паушальные, роялти и мерч. Роялти новых школ считается
    по возрастам: у каждой когорты своя ёмкость и свой минимальный платёж."""
    С = "'03_Сеть'"
    л = V.Лист(wb["04_Доходы"], "Доходы: паушальные, роялти, мерч",
               "Расшифровка к «Результату». Роялти новых школ разложено по "
               "возрасту школы: чем старше школа, тем больше в ней детей.")
    л.шапка()

    л.блок("Множители периода")
    r_инд = л.ряд("Индекс цен", "='07_Тарифы'!{т}$4", "коэфф.",
                  "Накопленная индексация из справочника тарифов",
                  формат="0.000", итог="конец")
    r_обор = л.ряд("Множитель оборота",
                   "=%s!{м}%d*МножительДетей*МножительЦен*{м}%d"
                   % (С, сеть["сезонность"], r_инд),
                   "коэфф.", "Сезонность, сценарные множители и индексация "
                             "в одном числе", формат="0.000", итог="среднее")
    r_ст_ст = л.ряд("Ставка роялти: договоры до перехода",
                    "={м}%d*IF(%s!{м}%d>=ДатаПереходаСтавки,СтавкаРоялтиВсех,"
                    "СтавкаРоялтиСтарых)" % (r_обор, С, сеть["дата"]),
                    "коэфф.", "После общей даты все переходят на единую ставку",
                    формат="0.0000", итог="среднее")
    r_ст_нов = л.ряд("Ставка роялти: договоры после перехода",
                     "={м}%d*IF(%s!{м}%d>=ДатаПереходаСтавки,СтавкаРоялтиВсех,"
                     "СтавкаРоялтиНовых)" % (r_обор, С, сеть["дата"]),
                     "коэфф.", "", формат="0.0000", итог="среднее")

    л.пусто()
    л.блок("Паушальные взносы")
    r_пауш_ндс = л.ряд("Паушальные взносы, с НДС",
                       "=%s!{м}%d*'07_Тарифы'!{т}$6" % (С, сеть["продажи"]),
                       "₽", "Продажи месяца по тарифу из справочника")
    r_пауш = л.ряд("Паушальные взносы, без НДС",
                   "={м}%d/(1+НДС)" % r_пауш_ндс, "₽", "", жирный=True)

    л.пусто()
    л.блок("Роялти действующей сети")
    # Роялти считается не котлом, а по группам точек начисления: внутри
    # каждой группы MAX(фикс; ставка х выручка группы), наружу — сумма.
    # MAX внутри SUMPRODUCT поэлементно не работает, поэтому берётся
    # тождество MAX(a,b) = (a + b + |a - b|) / 2.
    выручка = "%s!{м}%d*'07_Тарифы'!{т}$8" % (С, сеть["дети_действ"])
    осталось = "IF(ШколыСтарт=0,0,%s!{м}%d/ШколыСтарт)" % (С, сеть["школы_действ"])
    ст = ("(ГруппыСтавка*(%s!{м}%d<ДатаПереходаСтавки)"
          "+СтавкаРоялтиВсех*(%s!{м}%d>=ДатаПереходаСтавки))"
          % (С, сеть["дата"], С, сеть["дата"]))
    a = f"ГруппыФикс*ГруппыТочек*{осталось}"
    b = f"({выручка})*ГруппыДоля*{ст}"
    r_роялти_д = л.ряд("Роялти действующей сети, с НДС",
                       f"=SUMPRODUCT(({a}+{b}+ABS({a}-{b}))/2)",
                       "₽", "По каждой группе точек начисления: процент с "
                            "выручки группы, но не меньше суммы фиксов этой "
                            "группы. Профиль групп — раздел 16 вводных.")

    л.пусто()
    л.блок("Школы по возрасту: договоры до перехода на новую ставку")
    r_legacy_откр = л.ряд("Открытия по старым договорам",
                          "=IF({i}-ЛагОткрытия<1,0,IF(INDEX(%s!$L%d:$BY%d,1,"
                          "{i}-ЛагОткрытия)<=ДатаLegacy,%s!{м}%d,0))"
                          % (С, сеть["дата"], сеть["дата"], С, сеть["открытия"]),
                          "шт.", "Школа считается «старой», если франшизу "
                                 "купили до граничной даты", формат=V.ШТУКИ)
    legacy = []
    предыдущая = None
    for возраст in range(1, 26):
        если = "={м}%d" % r_legacy_откр if возраст == 1 else (
            "={пред}%d*КоэффСохранения" % предыдущая if возраст < 25
            else "=({пред}%d+{пред}{r})*КоэффСохранения" % предыдущая)
        r = л.ряд(f"{возраст} мес." if возраст < 25 else "25+ мес.", если,
                  "шт.", "", формат=V.ШТУКИ,
                  первый=("={м}%d" % r_legacy_откр) if возраст == 1 else "=0",
                  итог="конец")
        legacy.append(r)
        предыдущая = r

    def ставка_за_школу(возраст, ставка_строка):
        """Роялти с одной школы данного возраста — как в исходной модели."""
        k = f"{возраст:02d}"
        return (f"IF(РоялтиПоГруппам=\"Да\","
                f"MeanMinAge{k}+{{м}}{ставка_строка}"
                f"*SUMIF(ThresholdAge{k},\"<\"&{{м}}{ставка_строка},WeightedRevAge{k})"
                f"-SUMIF(ThresholdAge{k},\"<\"&{{м}}{ставка_строка},WeightedMinAge{k}),"
                f"MAX(CapacityAge{k}*АбонементНовых*{{м}}{ставка_строка},MeanMinAge{k}))")

    л.пусто()
    л.блок("Роялти новых школ по возрасту — старая ставка")
    стар = []
    for возраст in range(1, 26):
        r = л.ряд(f"{возраст} мес." if возраст < 25 else "25+ мес.",
                  "=IF(OR({м}%d=0,%d<=КаникулыРоялти),0,{м}%d*%s)"
                  % (legacy[возраст - 1], возраст, legacy[возраст - 1],
                     ставка_за_школу(возраст, r_ст_ст)),
                  "₽", "")
        стар.append(r)

    л.пусто()
    л.блок("Роялти новых школ по возрасту — новая ставка")
    нов = []
    когорты = сеть["когорты"]
    for возраст in range(1, 26):
        всего = "%s!{м}%d" % (С, когорты[возраст - 1])
        новых = f"({всего}-{{м}}{legacy[возраст - 1]})"
        r = л.ряд(f"{возраст} мес." if возраст < 25 else "25+ мес.",
                  "=IF(OR(%s=0,%d<=КаникулыРоялти),0,%s*%s)"
                  % (новых, возраст, новых, ставка_за_школу(возраст, r_ст_нов)),
                  "₽", "")
        нов.append(r)

    л.пусто()
    л.блок("Итог по роялти")
    r_роялти_н = л.ряд("Роялти новых школ, с НДС",
                       "=SUM({м}%d:{м}%d)+SUM({м}%d:{м}%d)"
                       % (стар[0], стар[24], нов[0], нов[24]), "₽",
                       "Сумма по всем возрастам и обеим ставкам")
    r_роялти_всего = л.ряд("Роялти всего, с НДС",
                           "={м}%d+{м}%d" % (r_роялти_д, r_роялти_н), "₽", "",
                           жирный=True)
    л.пусто()
    л.блок("Мерч: сколько комплектов покупают")
    r_сез_м = л.ряд("Сезонность повторных покупок",
                    "=INDEX('01_Вводные'!$B$94:$M$94,1,MONTH(%s!{м}%d))"
                    % (С, сеть["дата"]), "%",
                    "Доля годовой закупки, приходящаяся на этот месяц",
                    формат=V.ПРОЦЕНТ, итог="среднее")
    # Сентябрь–декабрь 2026 у действующей сети заданы фактом (раздел 5а
    # вводных). Месяц ищется по дате, а не по номеру столбца: при старте
    # позже сентября первый месяц забирал бы сентябрьские 5 070 комплектов.
    ФАКТ_КЛЮЧ = "'01_Вводные'!$B$98:$E$98"
    факт = lambda стр: (
        f"IF(COUNTIF({ФАКТ_КЛЮЧ},{С}!{{м}}{сеть['дата']})>0,"
        f"SUMIF({ФАКТ_КЛЮЧ},{С}!{{м}}{сеть['дата']},"
        f"'01_Вводные'!$B${стр}:$E${стр}),%s)")
    r_компл_д = л.ряд("Действующая сеть — комплекты",
                      "=" + факт(99) % ("%s!{м}%d*КоэффМерча*{м}%d"
                                        % (С, сеть["дети_база"], r_сез_м)),
                      "шт.", "Дети действующей сети по норме комплектов на "
                             "ребёнка, разложено сезонностью. Сентябрь–декабрь "
                             "2026 — согласованный факт из раздела 5а вводных",
                      формат=V.ШТУКИ)

    r_повтор = []
    л.блок("Школы, покупающие форму повторно (по возрасту)")
    когорты = сеть["когорты"]
    for возраст in range(1, 13):
        # школы моложе пяти месяцев форму повторно не покупают: у них ещё
        # идёт первичная закупка, растянутая на три месяца
        if возраст <= 4:
            формула = "=0"
            как = ("Школы моложе пяти месяцев повторно не закупаются — у них "
                   "ещё идёт первичная закупка") if возраст == 1 else ""
        else:
            формула = ("=IF(AND(ПравилоПовтора=\"Новый сезон\","
                       "%d-1>MOD(MONTH(%s!{м}%d)-9,12)),%s!{м}%d*CapacityAge%02d"
                       "*МножительДетей,0)"
                       % (возраст, С, сеть["дата"], С, когорты[возраст - 1],
                          возраст))
            как = ("Покупают заново, если уже пережили начало сезона"
                   if возраст == 5 else "")
        r = л.ряд(f"{возраст} мес.", формула, "чел.", как,
                  формат=V.ШТУКИ, итог="конец")
        r_повтор.append(r)
    r_повтор_ст = л.ряд("13 мес. и старше",
                        "=SUMPRODUCT(%s!{м}%d:{м}%d,CapacityYear2)*МножительДетей"
                        "+%s!{м}%d*CapacityAge25*МножительДетей"
                        % (С, когорты[12], когорты[23], С, когорты[24]),
                        "чел.", "Школы старше года покупают форму каждый сезон",
                        формат=V.ШТУКИ, итог="конец")
    r_дети_повтор = л.ряд("Дети для повторной формы — всего",
                          "=SUM({м}%d:{м}%d)+{м}%d"
                          % (r_повтор[0], r_повтор[11], r_повтор_ст),
                          "чел.", "", формат=V.ШТУКИ, итог="конец")

    о = сеть["открытия"]
    r_перв = л.ряд("Первичная закупка новых школ, комплекты",
                   "=(%s!{пред}%d*ПервичнаяМес1*КоэффСохранения"
                   "+%s!{пред2}%d*ПервичнаяМес2*КоэффСохранения^2"
                   "+%s!{пред3}%d*ПервичнаяМес3*КоэффСохранения^3)"
                   "*ДетиК12Мес*КоэффМерча" % (С, о, С, о, С, о),
                   "шт.", "Комплекты для только что открывшихся школ: закупка "
                          "растянута на три месяца после открытия",
                   формат=V.ШТУКИ, первый="=0")
    # во втором и третьем месяце слагаемых меньше — предыдущих открытий ещё нет
    л.ws.cell(row=r_перв, column=V.КОЛ_МЕС1 + 1).value = (
        f"=({С}!{V.мес(1)}{о}*ПервичнаяМес1*КоэффСохранения)*ДетиК12Мес*КоэффМерча")
    л.ws.cell(row=r_перв, column=V.КОЛ_МЕС1 + 2).value = (
        f"=({С}!{V.мес(2)}{о}*ПервичнаяМес1*КоэффСохранения"
        f"+{С}!{V.мес(1)}{о}*ПервичнаяМес2*КоэффСохранения^2)*ДетиК12Мес*КоэффМерча")
    r_повт_компл = л.ряд("Повторная закупка новых школ, комплекты",
                         "={м}%d*КоэффМерча*{м}%d" % (r_дети_повтор, r_сез_м),
                         "шт.", "", формат=V.ШТУКИ)

    л.пусто()
    л.блок("Мерч: деньги")
    r_выр_н = л.ряд("Новые школы — выручка с НДС",
                    "=({м}%d+{м}%d)*'07_Тарифы'!{т}$10" % (r_перв, r_повт_компл), "₽", "")
    r_cogs_н = л.ряд("Новые школы — COGS",
                     "=({м}%d+{м}%d)*'07_Тарифы'!{т}$9" % (r_перв, r_повт_компл), "₽", "")
    r_выр_д = л.ряд("Действующая сеть — выручка с НДС",
                    "=" + факт(100) % ("{м}%d*'07_Тарифы'!{т}$10" % r_компл_д),
                    "₽", "Сентябрь–декабрь 2026 — согласованный факт")
    r_cogs_д = л.ряд("Действующая сеть — COGS",
                     "=" + факт(101) % ("{м}%d*'07_Тарифы'!{т}$9" % r_компл_д),
                     "₽", "Сентябрь–декабрь 2026 — согласованный факт")

    r_мерч_ндс = л.ряд("Выручка мерча, с НДС",
                       "={м}%d+{м}%d" % (r_выр_д, r_выр_н), "₽", "")
    r_мерч = л.ряд("Выручка мерча, без НДС", "={м}%d/(1+НДС)" % r_мерч_ндс,
                   "₽", "", жирный=True)
    r_cogs = л.ряд("COGS мерча", "={м}%d+{м}%d" % (r_cogs_д, r_cogs_н), "₽", "")
    r_лог = л.ряд("Логистика, возвраты, брак",
                  "={м}%d*ЛогистикаМерча" % r_мерч, "₽", "")
    r_приб = л.ряд("Прибыль мерча до доли ФК",
                   "=MAX(0,{м}%d-{м}%d-{м}%d)" % (r_мерч, r_cogs, r_лог),
                   "₽", "Ниже нуля не опускается: делить убыток с клубом нечем",
                   жирный=True)

    log.append("04_Доходы: паушальные, роялти по 25 возрастам, мерч")
    return {"паушальные": r_пауш, "паушальные_ндс": r_пауш_ндс,
            "роялти_действ": r_роялти_д, "роялти_новых": r_роялти_н,
            "роялти_всего": r_роялти_всего, "индекс": r_инд,
            "множитель_оборота": r_обор, "legacy": legacy,
            "мерч": r_мерч, "мерч_ндс": r_мерч_ндс, "cogs": r_cogs,
            "логистика": r_лог, "прибыль_мерча": r_приб,
            "комплекты_первичка": r_перв, "комплекты_повтор": r_повт_компл,
            "лист": л}


def построить_расходы(wb, сеть, доходы, log):
    """05_Расходы — ФОТ с премиями, операционные расходы и выплаты клубу."""
    С, Д = "'03_Сеть'", "'04_Доходы'"
    л = V.Лист(wb["05_Расходы"], "Расходы: ФОТ, операционные, выплаты клубу",
               "Расшифровка к «Результату». Оклады индексируются раз в год, "
               "премии привязаны к продажам и числу партнёров.")
    л.шапка()
    дата = "%s!{м}%d" % (С, сеть["дата"])
    инд = "%s!{м}%d" % (Д, доходы["индекс"])

    л.блок("Оклады")
    r_индзп = л.ряд("Индекс окладов",
                    "=(1+ИнфляцияЗарплат)^MAX(0,YEAR(%s)-YEAR(ДатаИндексацииЗП)"
                    "+IF(MONTH(%s)>=MONTH(ДатаИндексацииЗП),1,0))" % (дата, дата),
                    "коэфф.", "Оклады индексируются каждое 1 сентября",
                    формат="0.000", итог="конец")
    r_гд = л.ряд("Повышение оклада ГД",
                 "=IF(%s>=ДатаПовышенияГД,ПовышениеГД/NetGross"
                 "*(1+ИнфляцияЗарплат)^MAX(0,YEAR(%s)-YEAR(ДатаПовышенияГД)"
                 "+IF(MONTH(%s)>=9,1,0)-IF(MONTH(ДатаПовышенияГД)>=9,1,0)),0)"
                 % (дата, дата, дата), "₽",
                 "Прибавка генеральному директору с назначенной даты")
    r_ядро = л.ряд("ФОТ ядра, gross",
                   "=ФОТЯдра*{м}%d+{м}%d" % (r_индзп, r_гд), "₽",
                   "Действующие сотрудники с индексацией")
    r_офм = л.ряд("Офис-менеджер, gross",
                  "=IF(%s>=ДатаОфисМенеджера,ОфисМенеджерNet/NetGross*{м}%d,0)"
                  % (дата, r_индзп), "₽", "Выходит с назначенной даты")
    r_смм = л.ряд("SMM-специалист, gross",
                  "=IF(%s>=ДатаSMM,SMMNet/NetGross*(1+ИнфляцияЗарплат)^"
                  "MAX(0,YEAR(%s)-YEAR(ДатаSMM)+IF(MONTH(%s)>=9,1,0)"
                  "-IF(MONTH(ДатаSMM)>=9,1,0)),0)" % (дата, дата, дата),
                  "₽", "")
    r_доп_кол = л.ряд("Доп. менеджеры развития",
                      "=MAX(0,MAX(БазовыхМенеджеров,INT(%s!{м}%d/ЮрлицНаМенеджера)+1)"
                      "-БазовыхМенеджеров)" % (С, сеть["юрлица"]),
                      "чел.", "Новый менеджер на каждые 35 партнёров",
                      формат=V.ШТУКИ, итог="конец")
    r_доп = л.ряд("Доп. менеджеры, gross",
                  "={м}%d*ОкладМенеджера*{м}%d" % (r_доп_кол, r_индзп), "₽", "")
    r_оклады = л.ряд("Все оклады, gross",
                     "={м}%d+{м}%d+{м}%d+{м}%d" % (r_ядро, r_офм, r_смм, r_доп),
                     "₽", "", жирный=True)
    r_взносы = л.ряд("Страховые взносы на оклады",
                     "={м}%d*СтраховыеВзносы" % r_оклады, "₽", "")

    л.пусто()
    л.блок("Премии")
    r_прем_разв = л.ряд("Премия развития, gross",
                        "=(БазовыхМенеджеров+{м}%d+1)*IF(%s<ДатаПремииРазвития,"
                        "ПремияРазвитияДо,ПремияРазвитияС)/NetGross"
                        % (r_доп_кол, дата), "₽",
                        "Всем менеджерам развития и проектному менеджеру")
    r_взн_разв = л.ряд("Взносы на премию развития",
                       "={м}%d*СтраховыеВзносы" % r_прем_разв, "₽", "")
    r_прем_евг = л.ряд("Премия Евгения, gross",
                       "=IF(%s!{м}%d>=2,%s!{м}%d*ПремияЕвгения"
                       "/(1+СтраховыеВзносы),0)"
                       % (С, сеть["продажи"], Д, доходы["паушальные"]), "₽",
                       "4% от паушальных — это вся стоимость премии для "
                       "компании, поэтому взносы уже внутри: gross получается "
                       "делением на 1,3")
    r_взн_евг = л.ряд("Взносы на премию Евгения",
                      "={м}%d*СтраховыеВзносы" % r_прем_евг, "₽", "")
    r_продавец = л.ряд("Временный продавец",
                       "=IF(%s!{м}%d>=ТриггерПродавца,IF(СтатусПродавца=\"ИП\","
                       "ПродавецФикс+%s!{м}%d*ПродавецБонус,"
                       "(ПродавецФикс/NetGross+%s!{м}%d*ПродавецБонус)"
                       "*(1+СтраховыеВзносы)),0)"
                       % (С, сеть["продажи"], Д, доходы["паушальные"],
                          Д, доходы["паушальные"]),
                       "₽", "Подключается при пяти продажах за месяц")
    r_кварт = л.ряд("Квартальная премия, gross",
                    "=IF(AND(%s>=ДатаКвартальных,MOD(MONTH(%s),3)=0),"
                    "(БазаКвартальной*{м}%d+IF(ПремияГДвБазе=\"Да\",{м}%d,0)"
                    "+{м}%d+{м}%d)*КвартальнаяПремия,0)"
                    % (дата, дата, r_индзп, r_гд, r_офм, r_смм), "₽",
                    "Раз в квартал, 60% месячного оклада")
    r_взн_кварт = л.ряд("Взносы на квартальную премию",
                        "={м}%d*СтраховыеВзносы" % r_кварт, "₽", "")

    л.пусто()
    л.блок("Разовые кадровые расходы")
    r_комис = л.ряд("Комиссия кадрового агентства",
                    "=(MAX(0,{м}%d-{пред}%d)*ОкладМенеджера*{м}%d"
                    "+IF(%s=ДатаОфисМенеджера,ОфисМенеджерNet/NetGross,0)"
                    "+IF(%s=ДатаSMM,SMMNet/NetGross,0))*КомиссияАгентства"
                    % (r_доп_кол, r_доп_кол, r_индзп, дата, дата), "₽",
                    "Один оклад за каждую новую штатную единицу",
                    первый="=(MAX(0,$L%d)*ОкладМенеджера*$L%d"
                           "+IF(%s=ДатаОфисМенеджера,ОфисМенеджерNet/NetGross,0)"
                           "+IF(%s=ДатаSMM,SMMNet/NetGross,0))*КомиссияАгентства"
                           % (r_доп_кол, r_индзп,
                              дата.replace("{м}", V.мес(1)),
                              дата.replace("{м}", V.мес(1))))
    r_замена = л.ряд("Замена директора маркетинга",
                     "=IF(%s=ДатаЗаменыДиректора,ЗаменаДиректора,0)" % дата, "₽", "")
    r_ротация = л.ряд("Резерв на ротацию кадров",
                      "=IF(MONTH(%s)=МесяцРезерва,'07_Тарифы'!{т}$14,0)" % дата,
                      "₽", "Раз в год")
    r_фот = л.ряд("ФОТ и кадровые расходы — всего",
                  "=SUM({м}%d,{м}%d,{м}%d,{м}%d,{м}%d,{м}%d,{м}%d,{м}%d,{м}%d,"
                  "{м}%d,{м}%d,{м}%d)"
                  % (r_оклады, r_взносы, r_прем_разв, r_взн_разв, r_прем_евг,
                     r_взн_евг, r_продавец, r_кварт, r_взн_кварт, r_комис,
                     r_замена, r_ротация), "₽", "", жирный=True)
    л.ws.cell(row=r_фот, column=2).value = "ФОТ и кадровые расходы — всего"

    л.пусто()
    л.блок("Операционные расходы")
    r_erp_подкл = л.ряд("Подключения школ к ERP",
                        "=IF({i}-ЛагERP<1,0,INDEX(%s!$L%d:$BY%d,1,{i}-ЛагERP)"
                        "*КоэффСохранения^ЛагERP)"
                        % (С, сеть["открытия"], сеть["открытия"]),
                        "шт.", "Подключение — отдельное событие после открытия",
                        формат=V.ШТУКИ)
    r_erp_акт = л.ряд("Новых школ в ERP",
                      "={пред}{r}*КоэффСохранения+{м}%d" % r_erp_подкл, "шт.",
                      "", первый="=$L%d" % r_erp_подкл, формат=V.ШТУКИ,
                      итог="конец")
    r_erp = л.ряд("ERP",
                  "=(ERPБаза+(MAX(0,%s!{м}%d-ERPШколВБазе)+{м}%d)*ERPНаШколу)*%s"
                  % (С, сеть["школы_действ"], r_erp_акт, инд), "₽",
                  "База плюс по 3 тыс. за каждую школу сверх базы")
    r_офис = л.ряд("Офис, аренда, уборка, парковка", "=Офис", "₽",
                   "До фактического переезда не меняется")
    r_юр = л.ряд("Юристы, аудит, бухгалтерия", "=Юристы*%s" % инд, "₽", "")
    r_it = л.ряд("Прочие IT", "=ПрочиеIT*%s" % инд, "₽", "")
    r_smm_подр = л.ряд("SMM и подрядчики", "='07_Тарифы'!{т}$13", "₽",
                       "После выхода штатного SMM тариф подрядчиков меняется")
    r_месяц_рекламы = л.ряд("Месяц оплаты рекламы за эти продажи",
                            "=DATE(YEAR(%s),MONTH(%s)-IF(%s=ДатаОсобогоЛага,"
                            "ОсобыйЛаг,ЛагТаргета),1)" % (дата, дата, дата),
                            "дата", "Обычно за два месяца до продажи; для "
                                    "октября 2026 — за один",
                            формат=V.ДАТА, итог="конец")
    r_таргет = л.ряд("Таргет на будущие продажи",
                     "=SUMIF($L%d:$BY%d,%s,%s!$L%d:$BY%d)*'07_Тарифы'!{т}$11"
                     % (r_месяц_рекламы, r_месяц_рекламы, дата,
                        С, сеть["продажи"], сеть["продажи"]),
                     "₽", "Собираем все продажи, чью рекламу оплачиваем в "
                          "этом месяце")
    r_размещ = л.ряд("БИБОСС, TopFranchise, Forbes",
                     "=(IF(MONTH(%s)=МесяцБИБОСС,СуммаБИБОСС,0)"
                     "+IF(MONTH(%s)=МесяцTopFranchise,СуммаTopFranchise,0)"
                     "+IF(MONTH(%s)=МесяцForbes,СуммаForbes,0))*%s"
                     % (дата, дата, дата, инд), "₽", "Ежегодные размещения")
    r_маркетинг = л.ряд("Маркетинг привлечения — всего",
                        "={м}%d+{м}%d" % (r_таргет, r_размещ), "₽", "")
    r_opex = л.ряд("OPEX — всего",
                   "={м}%d+{м}%d+{м}%d+{м}%d+{м}%d+{м}%d+{м}%d"
                   % (r_фот, r_erp, r_офис, r_юр, r_it, r_smm_подр, r_маркетинг),
                   "₽", "", жирный=True)

    л.пусто()
    л.блок("Выплаты футбольному клубу")
    r_фк_пауш = л.ряд("Начислено ФК: паушальные",
                      "=%s!{м}%d*ДоляФКПаушальные" % (Д, доходы["паушальные"]),
                      "₽", "")
    r_фк_роялти = л.ряд("Начислено ФК: роялти",
                        "=%s!{м}%d/(1+НДС)*ДоляФКРоялти"
                        % (Д, доходы["роялти_всего"]), "₽", "")
    r_фк_мерч = л.ряд("Начислено ФК: прибыль мерча",
                      "=%s!{м}%d*ДоляФКМерч" % (Д, доходы["прибыль_мерча"]),
                      "₽", "")
    r_фк = л.ряд("Начислено ФК — всего",
                 "={м}%d+{м}%d+{м}%d" % (r_фк_пауш, r_фк_роялти, r_фк_мерч),
                 "₽", "", жирный=True)

    log.append("05_Расходы: ФОТ с премиями, OPEX, начисления клубу")
    return {"фот": r_фот, "erp": r_erp, "офис": r_офис, "юристы": r_юр,
            "it": r_it, "smm": r_smm_подр, "маркетинг": r_маркетинг,
            "opex": r_opex, "фк_пауш": r_фк_пауш, "фк_роялти": r_фк_роялти,
            "фк_мерч": r_фк_мерч, "фк_всего": r_фк, "оклады": r_оклады,
            "erp_актив": r_erp_акт, "лист": л}


def построить_деньги(wb, сеть, доходы, расходы, log):
    """06_Деньги — склад, займ, CAPEX и налоги. Всё, что отличает
    начисление от денег."""
    С, Д, Р, Рез = "'03_Сеть'", "'04_Доходы'", "'05_Расходы'", "'02_Результат'"
    л = V.Лист(wb["06_Деньги"], "Деньги: склад, займ, CAPEX, налоги",
               "Расшифровка к «Результату». Здесь живёт всё, из-за чего "
               "денежный поток не равен EBITDA.")
    л.шапка()
    дата = "%s!{м}%d" % (С, сеть["дата"])

    л.блок("Товарный запас")
    r_скл_нач = л.ряд("Склад на начало", "={пред}{r}+0", "₽",
                      "Остаток предыдущего месяца",
                      первый="=СкладСтарт", формат=V.ДЕНЬГИ, итог="конец")
    r_списание = л.ряд("Списание по себестоимости", "=%s!{м}%d" % (Д, доходы["cogs"]),
                       "₽", "COGS проданного мерча")
    r_цель = л.ряд("Целевой запас будущих продаж",
                   "=SUM(IF(ЗапасМес>=1,%s!{след1}%d,0),IF(ЗапасМес>=2,%s!{след2}%d,0),"
                   "IF(ЗапасМес>=3,%s!{след3}%d,0),IF(ЗапасМес>=4,%s!{след4}%d,0),"
                   "IF(ЗапасМес>=5,%s!{след5}%d,0),IF(ЗапасМес>=6,%s!{след6}%d,0))"
                   % tuple([Д, доходы["cogs"]] * 6), "₽",
                   "Себестоимость продаж на ближайшие месяцы вперёд",
                   итог="конец")
    r_закупка = л.ряд("Закупка на склад",
                      "=IF(AND(%s>=СтартПополнения,OR(MONTH(%s)=МесяцЗакупки1,"
                      "MONTH(%s)=МесяцЗакупки2,MONTH(%s)=МесяцЗакупки3,"
                      "MONTH(%s)=МесяцЗакупки4)),MAX(0,{м}%d-({м}%d-{м}%d)),0)"
                      % (дата, дата, дата, дата, дата, r_цель, r_скл_нач,
                         r_списание), "₽",
                      "Закупаем четыре раза в год, доводя склад до цели")
    r_скл_кон = л.ряд("Склад на конец",
                      "={м}%d+{м}%d-{м}%d" % (r_скл_нач, r_закупка, r_списание),
                      "₽", "Минус означает необеспеченный спрос", жирный=True,
                      итог="конец")
    # «на начало» — это «на конец» предыдущего месяца
    for i in range(2, V.ВСЕГО_МЕСЯЦЕВ + 1):
        л.ws.cell(row=r_скл_нач, column=V.КОЛ_МЕС1 + i - 1).value = \
            f"={V.мес(i - 1)}{r_скл_кон}"

    r_порог = л.ряд("Минимальный запас для возврата займа",
                    "=SUM(IF(ЗапасДляЗайма>=1,%s!{след1}%d,0),"
                    "IF(ЗапасДляЗайма>=2,%s!{след2}%d,0),"
                    "IF(ЗапасДляЗайма>=3,%s!{след3}%d,0),"
                    "IF(ЗапасДляЗайма>=4,%s!{след4}%d,0),"
                    "IF(ЗапасДляЗайма>=5,%s!{след5}%d,0),"
                    "IF(ЗапасДляЗайма>=6,%s!{след6}%d,0))"
                    % tuple([Д, доходы["cogs"]] * 6), "₽",
                    "Займ отдаём, только если склада хватает на столько "
                    "месяцев вперёд. Это не то же, что целевой запас закупки",
                    итог="конец")

    л.пусто()
    л.блок("Займ на мерч")
    r_займ_нач = л.ряд("Займ на начало", "={пред}{r}+0", "₽", "",
                       первый="=ЗаймСтарт", итог="конец")
    r_погаш_баз = л.ряд("Базовое погашение",
                        "=MIN({м}%d,%s!{м}%d*ДоляCOGSНаЗайм)"
                        % (r_займ_нач, Д, доходы["cogs"]), "₽",
                        "60% себестоимости проданного мерча")
    # Из остатка вычитается МинОстатокДляЗайма: ниже этого порога клубу не
    # платим. При нуле модель отдавала деньги до нуля на счёте и уходила в
    # минус на следующем же крупном платеже.
    r_погаш = л.ряд("Погашение с учётом денег и склада",
                    "=IF(OR(ОграничитьЗайм=\"Нет\",{м}%d>={м}%d-0.01),"
                    "MIN({м}%d,MAX(0,@@РЕЗ_деньги_до_займа@@"
                    "-МинОстатокДляЗайма)),0)"
                    % (r_скл_кон, r_порог, r_погаш_баз), "₽",
                    "Платим, только если склад не ниже цели, а на счёте "
                    "остаётся минимальный остаток")
    r_займ_кон = л.ряд("Займ на конец",
                       "={м}%d-{м}%d" % (r_займ_нач, r_погаш), "₽", "",
                       жирный=True, итог="конец")
    for i in range(2, V.ВСЕГО_МЕСЯЦЕВ + 1):
        л.ws.cell(row=r_займ_нач, column=V.КОЛ_МЕС1 + i - 1).value = \
            f"={V.мес(i - 1)}{r_займ_кон}"

    л.пусто()
    л.блок("CAPEX и налоги")
    r_база_capex = л.ряд("База CAPEX",
                         "=IF(CAPEXБаза=\"С НДС\",(%s!{м}%d+%s!{м}%d/(1+НДС)"
                         "+%s!{м}%d)*(1+НДС),%s!{м}%d+%s!{м}%d/(1+НДС)+%s!{м}%d)"
                         % (Д, доходы["паушальные"], Д, доходы["роялти_всего"],
                            Д, доходы["мерч"], Д, доходы["паушальные"],
                            Д, доходы["роялти_всего"], Д, доходы["мерч"]),
                         "₽", "Выручка, от которой считается поддерживающий CAPEX")
    r_capex = л.ряд("CAPEX — всего",
                    "=IF(CAPEXВключён=\"Да\",{м}%d*CAPEXДоля,0)"
                    "+IF(AND(CAPEXВключён=\"Да\",%s=CAPEXДата),CAPEXРазовый,0)"
                    % (r_база_capex, дата), "₽", "")
    r_налог = л.ряд("УСН / минимальный налог",
                    "=MAX(МинНалог*@@РЕЗ_выручка@@,СтавкаУСН*MAX(0,@@РЕЗ_ebitda@@))", "₽",
                    "Что больше: минимальный налог с выручки или УСН с прибыли")
    r_ндс = л.ряд("НДС основной деятельности",
                  "=(@@РЕЗ_пост_пауш@@+@@РЕЗ_пост_роялти@@+@@РЕЗ_пост_мерч@@)"
                  "-(@@РЕЗ_пост_пауш@@+@@РЕЗ_пост_роялти@@+@@РЕЗ_пост_мерч@@)/(1+НДС)",
                  "₽", "")

    л.пусто()
    л.блок("Оборотный капитал")
    r_деб = л.ряд("Дебиторка роялти на конец",
                  "={пред}{r}+%s!{м}%d/(1+НДС)-@@РЕЗ_пост_роялти@@/(1+НДС)"
                  % (Д, доходы["роялти_всего"]), "₽",
                  "Начислили минус получили",
                  первый="=%s!$L%d/(1+НДС)-@@РЕЗ_пост_роялти@@/(1+НДС)"
                         % (Д, доходы["роялти_всего"]), итог="конец")
    r_кред = л.ряд("Кредиторка перед поставщиками",
                   "={пред}{r}+%s!{м}%d+{м}%d-@@РЕЗ_оплата_поставщикам@@"
                   % (Р, расходы["opex"], r_закупка), "₽", "Начислили минус оплатили",
                   первый="=%s!$L%d+$L%d-@@РЕЗ_оплата_поставщикам@@"
                   % (Р, расходы["opex"], r_закупка), итог="конец")
    r_фк_долг = л.ряд("Долг перед клубом по операционным выплатам",
                      "={пред}{r}+%s!{м}%d-@@РЕЗ_оплата_фк@@" % (Р, расходы["фк_всего"]),
                      "₽", "", первый="=%s!$L%d-@@РЕЗ_оплата_фк@@"
                      % (Р, расходы["фк_всего"]), итог="конец")

    log.append("06_Деньги: склад, займ, CAPEX, налоги, оборотка")
    return {"склад_нач": r_скл_нач, "списание": r_списание, "цель": r_цель,
            "закупка": r_закупка, "склад_кон": r_скл_кон,
            "займ_нач": r_займ_нач, "погашение": r_погаш, "займ_кон": r_займ_кон,
            "capex": r_capex, "налог": r_налог, "ндс": r_ндс,
            "дебиторка": r_деб, "кредиторка": r_кред, "долг_фк": r_фк_долг,
            "лист": л}


def построить_результат(wb, сеть, доходы, расходы, деньги, log):
    """02_Результат — то, ради чего всё считалось: БДР и БДДС рядом."""
    С, Д, Р, ДЕН = "'03_Сеть'", "'04_Доходы'", "'05_Расходы'", "'06_Деньги'"
    л = V.Лист(wb["02_Результат"], "Результат: БДР и БДДС",
               "Начисления и деньги на одном листе, но в разных блоках. "
               "Слева итоги по годам, справа те же строки по месяцам.")
    л.шапка(дата_строка=None)

    л.блок("Сеть (справочно)")
    л.ряд("Школы всего", "=%s!{м}%d" % (С, сеть["школы_всего"]), "шт.",
          "Подробности — на листе «Сеть»", формат=V.ШТУКИ, итог="конец")
    л.ряд("Партнёры (юрлица)", "=%s!{м}%d" % (С, сеть["юрлица"]), "шт.", "",
          формат=V.ШТУКИ, итог="конец")
    л.ряд("Дети, активные", "=%s!{м}%d" % (С, сеть["дети_всего"]), "чел.", "",
          формат=V.ШТУКИ, итог="конец")

    л.пусто()
    л.блок("БДР — начисления")
    r_пауш = л.ряд("Паушальные взносы", "=%s!{м}%d" % (Д, доходы["паушальные"]),
                   "₽", "Без НДС")
    r_роялти = л.ряд("Роялти", "=%s!{м}%d/(1+НДС)" % (Д, доходы["роялти_всего"]),
                     "₽", "Без НДС")
    r_мерч = л.ряд("Мерч", "=%s!{м}%d" % (Д, доходы["мерч"]), "₽", "Без НДС")
