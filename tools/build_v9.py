def связать_с_результатом(wb, адреса, log):
    """Второй проход: в листе денег заменяем маркеры на адреса строк
    результата. Так два листа могут ссылаться друг на друга, а порядок
    сборки остаётся однонаправленным."""
    ws = wb["06_Деньги"]
    заменено = 0
    for row in ws.iter_rows():
        for c in row:
            if not isinstance(c.value, str) or "@@РЕЗ_" not in c.value:
                continue
            знач = c.value
            for ключ, строка in адреса.items():
                маркер = f"@@РЕЗ_{ключ}@@"
                if маркер in знач:
                    колонка = c.column_letter
                    знач = знач.replace(маркер, f"'02_Результат'!{колонка}{строка}")
            c.value = знач
            заменено += 1
    log.append(f"СВЯЗЬ: в 06_Деньги подставлено {заменено} ссылок на результат")


