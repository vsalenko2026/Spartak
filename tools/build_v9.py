def _строка_вводных(wb, название, после=None):
    """Строка листа вводных по подписи в колонке A."""
    v = wb["01_Вводные"]
    старт = 1
    if после:
        старт = next(r for r in range(1, v.max_row + 1)
                     if str(v.cell(r, 1).value or "").startswith(после))
    for r in range(старт, v.max_row + 1):
        if v.cell(r, 1).value == название:
            return r
    raise SystemExit(f"01_Вводные: не найдена строка {название!r}")


