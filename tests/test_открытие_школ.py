# -*- coding: utf-8 -*-
"""Партнёр открывает свои школы не в один месяц.

До 11.09.2026 коэффициент «школ на партнёра» (B22 = 1,5) применялся целиком
в месяц открытия: каждая продажа сразу давала полторы школы. В жизни
партнёр запускает одну площадку, а следующие берёт позже. Тесты следят,
чтобы коэффициент снова не схлопнулся в один месяц.
"""


def _вводные(base):
    вв = base.data["inputs"]
    return (вв["лаг_открытия"], вв["школ_на_партнёра"],
            вв["конверсия"], вв["лаг_следующих_школ"])


def test_первая_школа_партнёра_одна(base):
    """В месяц первого открытия на одну продажу приходится ровно одна
    школа, а не полторы: остальные ещё не открылись."""
    лаг, школ, конв, лаг2 = _вводные(base)
    if лаг2 == 0:
        return                        # выключено осознанно — проверять нечего
    продажи = base.series("Продажи", block="сеть")
    открытия = base.series("Открытия школ", block="сеть")
    первый = next((i for i, v in enumerate(продажи) if v > 0), None)
    assert первый is not None, "в прогоне нет ни одной продажи"
    м = первый + int(лаг)
    ожидаем = продажи[первый] * конв * min(1, школ)
    факт = открытия[м]
    assert abs(факт - ожидаем) < 0.01, (
        f"в месяц {м + 1} открылось {факт:.2f} школы на {продажи[первый]:.2f} "
        f"продажи — ожидалась одна школа на продажу ({ожидаем:.2f}), "
        f"значит коэффициент {школ} применился разом")


def test_вторая_школа_доезжает_позже(base):
    """Коэффициент не потерян: школы сверх первой открываются, просто
    позже. За горизонт уезжает только хвост последних продаж."""
    лаг, школ, конв, лаг2 = _вводные(base)
    if школ <= 1:
        return
    продажи = base.series("Продажи", block="сеть")
    открытия = base.series("Открытия школ", block="сеть")
    всего_продаж = sum(продажи)
    assert sum(открытия) > всего_продаж * конв * 1.0, (
        "открытий не больше, чем продаж — школы сверх первой потерялись, "
        f"а не сдвинулись (B22 = {школ})")
    assert sum(открытия) < всего_продаж * конв * школ + 0.01, (
        "открытий больше, чем даёт коэффициент — где-то удвоение")
