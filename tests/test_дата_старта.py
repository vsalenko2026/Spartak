"""Модель должна считаться от любой даты старта, не только от сентября.

Две вещи были привязаны к номеру столбца, а не к календарю, и молча
ломались при любом другом старте: веса плана продаж (таблица подписана
Сен…Авг) и согласованный мерч сентября–декабря 2026, который стоял в
первых четырёх столбцах листа мерча. Тесты не дают этому вернуться.
"""
import os
import sys
from pathlib import Path

import pytest

sys.path.insert(0, str(Path(__file__).resolve().parent.parent / "tools"))

from conftest import Run, close, ensure_run          # noqa: E402
from run_model import checks_summary                 # noqa: E402


@pytest.fixture(scope="session")
def декабрь():
    """Тот же базовый сценарий, но старт на три месяца позже.

    Тег привязан к базовому: под selfcheck базовый срез считается с
    испорченной модели, и декабрьский должен считаться с неё же, иначе
    подсаженный дефект сюда просто не доедет."""
    база = os.environ.get("SPARTAK_BASE_TAG", "база")
    return Run(ensure_run(f"{база}_декабрь",
                          ["--set", "01_Вводные!B7=2026-12-01"]))


def test_старт_в_декабре_считается_без_ошибок(декабрь):
    ошибки = декабрь.data["cell_errors"]
    assert not ошибки, ("при старте в декабре в ячейках появились ошибки: "
                        + ", ".join(str(e) for e in ошибки[:5]))


СТАРТ_ДЕКАБРЬ = 12          # месяц старта декабрьского прогона


def test_план_сезона_выполняется_целиком_при_любом_старте(base, декабрь):
    """Сколько бы ни был сдвинут старт, за каждый сезон должно продаться
    ровно столько франшиз, сколько стоит в плане сезона."""
    эталон = base.series("Продажи", block="сеть")
    по_сезонам = [sum(эталон[i * 12:(i + 1) * 12]) for i in range(5)]
    продажи = декабрь.series("Продажи", block="сеть")
    for n in range(5):
        факт = sum(продажи[n * 12:(n + 1) * 12])
        close(по_сезонам[n], факт,
              f"декабрьский старт: сезон {n + 1} продал {факт:.2f} "
              f"вместо плановых {по_сезонам[n]:.2f}", rel=1e-6)


def test_пик_продаж_стоит_на_сентябре_а_не_на_первом_месяце(декабрь):
    """Самый сильный месяц в таблице весов — сентябрь (0,18). Он должен
    остаться сентябрём и при сдвинутом старте.

    Это и есть та ошибка, ради которой тест написан: если вес берётся по
    номеру месяца в сезоне, а не по календарю, сентябрьские 18 % достаются
    первому месяцу сезона — при декабрьском старте декабрю."""
    продажи = декабрь.series("Продажи", block="сеть")
    сезон2 = продажи[12:24]              # первый полный сезон
    assert max(сезон2) > 0, "во втором сезоне нет продаж"
    # месяц 13 — это декабрь следующего года, дальше по кругу
    календарь = [(СТАРТ_ДЕКАБРЬ - 1 + i) % 12 + 1 for i in range(12)]
    пик = календарь[сезон2.index(max(сезон2))]
    assert пик == 9, (
        f"пик продаж второго сезона пришёлся на месяц {пик}, а не на "
        f"сентябрь — веса плана берутся по номеру месяца в сезоне, "
        f"а не по календарю")


def test_согласованный_мерч_не_съезжает(декабрь):
    """Факт сентября–декабря 2026 привязан к датам. При старте в декабре
    в горизонт попадает только декабрь — 720 комплектов, а не
    сентябрьские 5 070."""
    компл = декабрь.series("Действующая сеть — комплекты", block="мерч")
    assert компл[0] < 2000, (
        f"первый месяц декабрьского прогона получил {компл[0]:.0f} "
        f"комплектов — это сентябрьский факт, съехавший на первый столбец")


def test_собственные_проверки_модели_при_другом_старте(декабрь):
    """Лист 13_Проверки не должен сыпаться от смены даты старта."""
    плохие = checks_summary(декабрь.data)
    assert not плохие, ("при старте в декабре не прошли проверки модели: "
                        + "; ".join(str(c) for c in плохие[:5]))
