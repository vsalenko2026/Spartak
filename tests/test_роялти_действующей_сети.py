# -*- coding: utf-8 -*-
"""Роялти действующей сети считается по группам точек начисления.

До 11.09.2026 оно считалось котлом: MAX(6,5 % с общего оборота;
число школ × 15 000). Котёл ошибается дважды — не видит льготных ставок и
берёт фикс с каждой школы, хотя счёт выставляется на точку начисления
(48 точек на 104 школы). Эти тесты не дают вернуться к котлу.
"""
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent / "tools"))

from build_user_friendly import ГРУППЫ_РОЯЛТИ  # noqa: E402

ФИКС_ВСЕГО = sum(точек * фикс for _, точек, _, фикс, _ in ГРУППЫ_РОЯЛТИ)
ТОЧЕК_ВСЕГО = sum(точек for _, точек, _, _, _ in ГРУППЫ_РОЯЛТИ)


def _данные(base):
    роялти = base.series("Роялти действующей сети, с НДС", block="сеть")
    школы = base.series("Действующая сеть — школы")
    школы_старт = школы[0] / 0.997  # первый месяц уже с коэффициентом закрытия
    пол = [ФИКС_ВСЕГО * ш / школы_старт for ш in школы]
    return роялти, пол


def test_роялти_не_ниже_суммы_фиксов(base):
    """Каждая точка платит свой фикс, даже если выручки нет совсем.
    Значит роялти месяца не может быть ниже суммы фиксов живых точек."""
    роялти, пол = _данные(base)
    плохие = [(i, r, p) for i, (r, p) in enumerate(zip(роялти, пол), 1)
              if r < p * 0.999]
    assert not плохие, (
        "роялти ниже суммы фиксов в месяцах: "
        + ", ".join(f"{i}: {r:,.0f} < {p:,.0f}" for i, r, p in плохие[:5]))


def test_фикс_берётся_с_точки_начисления_а_не_со_школы(base):
    """Летом выручка падает и роялти ложится на фикс. В этот момент видно,
    с чего он берётся: 48 точек по среднему фиксу дают около 828 тыс.,
    а котёл со 104 школ по 15 000 дал бы 1,56 млн — почти вдвое больше."""
    роялти, пол = _данные(base)
    у_пола = [i for i, (r, p) in enumerate(zip(роялти, пол), 1)
              if r <= p * 1.01]
    assert у_пола, (
        "ни в одном месяце роялти не опустилось до суммы фиксов — "
        "либо фиксы перестали работать, либо вернулся котёл")
    самый_низкий = min(роялти)
    котёл = 104 * 15_000 * 0.86       # 104 школы по 15 000 к концу горизонта
    assert самый_низкий < котёл * 0.8, (
        f"минимальное роялти {самый_низкий:,.0f} ₽ — это уровень котла "
        f"«школы × 15 000», а не суммы фиксов {ФИКС_ВСЕГО:,.0f} ₽ "
        f"с {ТОЧЕК_ВСЕГО} точек начисления")


def test_доли_выручки_в_профиле_дают_сто_процентов():
    """Профиль групп — это разложение одной и той же выручки сети.
    Если доли перестали давать единицу, часть оборота потерялась."""
    сумма = sum(доля for _, _, доля, _, _ in ГРУППЫ_РОЯЛТИ)
    assert abs(сумма - 1) < 1e-6, (
        f"доли выручки групп дают {сумма:.4f} вместо 1,0000")
