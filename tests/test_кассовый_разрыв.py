# -*- coding: utf-8 -*-
"""Возврат займа клубу не имеет права опустошать счёт.

До 11.09.2026 порог остатка `B237` стоял нулём, и формула
`MAX(0; остаток − B237)` разрешала отдавать клубу деньги до нуля на
счёте. В первый же месяц модель отдавала 3 075 292 ₽, имея на старте
187 878 ₽, — и дальше двенадцать месяцев подряд жила с отрицательной
кассой, глубиной до −8,7 млн. Отрицательный расчётный счёт — это не
сценарий, а невозможность: так бизнес не работает.
"""


def test_порог_остатка_при_возврате_займа_не_нулевой(base):
    """Ноль в пороге означает «платим клубу до нуля на счёте».

    Проверка отдельная от следующей: та сверяет модель с порогом, каким
    бы он ни был, и при нулевом пороге проходит вхолостую."""
    порог = base.data["inputs"]["порог_остатка_займа"]
    assert порог > 0, (
        "порог остатка при возврате займа снова нулевой: модель отдаст "
        "клубу все свободные деньги и уйдёт в минус на следующем же "
        "крупном платеже")


def test_возврат_займа_не_опускает_остаток_ниже_порога(base):
    """В месяце, когда клубу что-то заплачено, на счёте должен остаться
    как минимум порог. Иначе платёж клубу профинансирован из воздуха."""
    порог = base.data["inputs"]["порог_остатка_займа"]
    погашение = base.series("Погашение займа")
    остаток = base.series("Денежный остаток на конец")
    плохие = [(i, п, о) for i, (п, о) in enumerate(zip(погашение, остаток), 1)
              if п > 1 and о < порог - 1]
    assert not плохие, (
        f"порог остатка {порог:,.0f} ₽ нарушен: "
        + "; ".join(f"месяц {i}: заплачено {п:,.0f}, осталось {о:,.0f}"
                    for i, п, о in плохие[:5]))


def test_счёт_не_уходит_в_минус(base):
    """Отрицательный расчётный счёт — не сценарий, а невозможность.

    Строки привлечения денег в БДДС нет и заводить её владелец модели
    решил не нужным (11.09.2026), поэтому любой минус в остатке — это
    платёж, который нечем сделать. С порогом остатка 10 млн и целевым
    запасом формы 3 месяца минуса нет ни в одном из 60 месяцев."""
    остаток = base.series("Денежный остаток на конец")
    минусы = [(i, o) for i, o in enumerate(остаток, 1) if o < 0]
    assert not минусы, (
        "счёт уходит в минус, а закрыть его нечем — "
        + "; ".join(f"месяц {i}: {o:,.0f} ₽" for i, o in минусы[:5]))


def test_порог_возврата_займа_не_выше_целевого_запаса(base):
    """Если порог выше цели, склад до него не дорастает и займ клубу
    перестаёт гаситься: при цели 3 и пороге 4 за пять лет возвращается
    6 млн из 50."""
    цель = base.data["inputs"]["целевой_запас_мес"]
    погашение = base.series("Погашение займа")
    заём = base.data["inputs"].get("порог_займа_мес")
    if заём is not None:
        assert заём <= цель + 1e-9, (
            f"порог возврата займа {заём} мес. выше целевого запаса "
            f"{цель} мес. — займ перестанет гаситься")
    assert sum(погашение) > 40_000_000, (
        f"за горизонт клубу возвращено всего {sum(погашение):,.0f} ₽ из "
        f"50 млн — проверьте, не выше ли порог возврата целевого запаса")


def test_первый_месяц_не_уходит_в_ноль(base):
    """Стартовых денег 187 878 ₽. Если после первого месяца на счёте
    ровно ноль, значит всё свободное ушло клубу — и запас не оставлен."""
    остаток = base.series("Денежный остаток на конец")
    assert остаток[0] > 1, (
        f"после первого месяца на счёте {остаток[0]:,.0f} ₽ — "
        f"модель отдала клубу всё, что было")
