# -*- coding: utf-8 -*-
"""Сеть и дети — то место, где модель ломают чаще всего.

Два правила, ради которых этот файл существует:
партнёров и школ нельзя приравнивать, а новая школа не набирает полную
загрузку в первый месяц.
"""
import pytest
from conftest import close_series


def test_дети_всего_равны_сумме(base):
    got = [a + b for a, b in zip(base.series("Действующая сеть — активные дети"),
                                 base.series("Новые школы — дети"))]
    close_series(base.series("Всего активных детей"), got,
                 "Всего детей ≠ дети действующей сети + дети новых школ")


def test_партнёров_не_больше_чем_школ(base):
    """Один партнёр держит несколько школ, поэтому школ всегда не меньше.
    Обратное означает, что где-то вернулось правило «1 партнёр = 1 школа»."""
    schools = [a + b for a, b in zip(base.series("Действующая сеть — школы"),
                                     base.series("Новые школы — активные школы"))]
    partners = base.series("Активные юрлица")
    bad = [(i, p, s) for i, (p, s) in enumerate(zip(partners, schools), 1) if p > s + 1e-6]
    assert not bad, ("партнёров больше, чем школ, в месяцах: "
                     + ", ".join(f"{i}: {p:.0f} > {s:.0f}" for i, p, s in bad[:5]))


def test_на_партнёра_приходится_больше_одной_школы(base):
    """Стартовая сеть — 51 партнёр и 104 школы, то есть около двух школ на
    партнёра. Если соотношение схлопнулось до единицы, экономика роялти
    посчитана не по школам."""
    schools = [a + b for a, b in zip(base.series("Действующая сеть — школы"),
                                     base.series("Новые школы — активные школы"))]
    partners = base.series("Активные юрлица")
    ratio = [s / p for p, s in zip(partners, schools) if p > 0]
    assert ratio, "нет ни одного месяца с активными партнёрами"
    assert max(ratio) > 1.2, (
        f"на партнёра приходится не больше {max(ratio):.2f} школы — "
        f"похоже, партнёры и школы отождествлены")


STAGES = [("1–12 мес.", "Новые школы — 1–12 мес.", "Новые школы - дети в мес. 1-12"),
          ("13–24 мес.", "Новые школы — 13–24 мес.", "Новые школы - дети в мес. 13-24"),
          ("зрелые", "Новые школы — зрелые", "Новые школы — дети зрелые")]


def _загрузка(base, месяц):
    """Детей на школу по каждой стадии жизни в конкретном месяце."""
    out = {}
    for name, школы, дети in STAGES:
        s = base.series(школы, "сеть")[месяц]
        k = base.series(дети, "сеть")[месяц]
        out[name] = k / s if s >= 1 else None
    return out


def test_новые_школы_набирают_детей_постепенно(base):
    """Загрузка школы обязана расти по стадиям жизни: 1–12 мес. < 13–24 мес.
    < зрелая. Сравниваем внутри одного месяца, поэтому сезонность одинакова
    для всех стадий и на результат не влияет.

    Средняя загрузка по всем новым школам для этого не годится: она растёт
    и без всякого набора — просто оттого, что старых школ в выборке
    становится больше."""
    месяцы = [i for i in range(60)
              if all(v is not None for v in _загрузка(base, i).values())]
    assert месяцы, "нет ни одного месяца, где представлены все три стадии"
    плохие = []
    for i in месяцы:
        z = _загрузка(base, i)
        if not (z["1–12 мес."] < z["13–24 мес."] < z["зрелые"]):
            плохие.append(f"месяц {i + 1}: {z['1–12 мес.']:.1f} / "
                          f"{z['13–24 мес.']:.1f} / {z['зрелые']:.1f}")
    assert not плохие, (
        "загрузка школы не растёт по стадиям жизни (дети на школу: "
        "1–12 / 13–24 / зрелые):\n  " + "\n  ".join(плохие[:6]))


def test_первый_год_заметно_ниже_зрелости(base):
    """Не просто «меньше», а существенно меньше: школа первого года не может
    стоять вплотную к зрелой, иначе постепенный набор превратился в
    формальность."""
    месяцы = [i for i in range(60)
              if all(v is not None for v in _загрузка(base, i).values())]
    assert месяцы, "нет месяцев со всеми стадиями"
    доли = [_загрузка(base, i)["1–12 мес."] / _загрузка(base, i)["зрелые"]
            for i in месяцы]
    худшая = max(доли)
    assert худшая < 0.9, (
        f"школа первого года набирает до {худшая:.0%} от зрелой загрузки — "
        f"постепенный набор фактически выключен")


def test_закрытие_школ_применяется_как_задано(base):
    """Закрытие задаётся процентом в год (01_Вводные!B13) и раскладывается
    в месячный коэффициент B14 = (1−B13)^(1/12). Действующая сеть новых
    школ не открывает, поэтому её ряд обязан убывать ровно этим
    коэффициентом — ни быстрее, ни медленнее.

    Тест ловит и потерю закрытия, и его двойное применение."""
    ставка = base.data.get("inputs", {}).get("закрытие_в_год")
    if ставка is None:
        pytest.skip("прогон сделан старой версией run_model.py, без вводных")
    ожидаемый = (1 - ставка) ** (1 / 12)
    ряд = base.series("Действующая сеть — школы")
    плохие = []
    for i, (a, b) in enumerate(zip(ряд, ряд[1:]), start=1):
        if a <= 0:
            continue
        факт = b / a
        if abs(факт - ожидаемый) > 1e-6:
            плохие.append(f"месяц {i}→{i+1}: {факт:.6f} вместо {ожидаемый:.6f}")
    assert not плохие, (
        f"действующая сеть убывает не по заданной ставке {ставка:.1%} в год:\n  "
        + "\n  ".join(плохие[:5]))


def test_закрытие_не_обгоняет_открытия(base):
    """Школы закрываются, но сеть в целом растёт: закрытие не должно
    съедать больше, чем приносят открытия."""
    школы = base.series("Новые школы — активные школы")
    assert школы[-1] > школы[11], (
        f"новых школ на конец {школы[-1]:.0f} против {школы[11]:.0f} на 12-й "
        f"месяц — сеть не растёт")


def test_дети_не_отрицательные(base):
    for label in ("Действующая сеть — активные дети", "Новые школы — дети",
                  "Всего активных детей"):
        bad = [(i, v) for i, v in enumerate(base.series(label), 1) if v < 0]
        assert not bad, f"«{label}» уходит в минус в месяцах {bad[:5]}"
